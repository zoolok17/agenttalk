def _root_key(value) -> str | None:
    if not isinstance(value, str):
        try:
            value = str(value)
        except Exception:  # noqa: BLE001 - root normalization is fail-closed
            return None
    value = value.strip()
    if not value:
        return None
    try:
        return str(Path(value).resolve(strict=False)).casefold()
    except (OSError, ValueError):
        return None


def _same_root(candidate: str | None, root_key: str | None) -> bool:
    return bool(candidate and root_key and _root_key(candidate) == root_key)


def _image_stem(row_or_name) -> str:
    name = row_or_name.get("name") if isinstance(row_or_name, dict) else row_or_name
    if not isinstance(name, str):
        return ""
    leaf = name.replace("\\", "/").rsplit("/", 1)[-1]
    if "." in leaf:
        leaf = leaf.rsplit(".", 1)[0]
    return leaf.casefold()


_SHELL_HOSTS = {
    "powershell",
    "pwsh",
    "cmd",
    "windowsterminal",
    "wt",
    "conhost",
    "openconsole",
    "explorer",
}


def _is_shell_host(row: dict | None) -> bool:
    return _image_stem(row or {}) in _SHELL_HOSTS


def _split_command_line(command_line: object) -> list[str] | None:
    if not isinstance(command_line, str) or not command_line.strip():
        return None
    try:
        raw = shlex.split(command_line, posix=False)
    except ValueError:
        return None
    out: list[str] = []
    for token in raw:
        if len(token) >= 2 and token[0] == token[-1] and token[0] in "\"'":
            token = token[1:-1]
        if token:
            out.append(token)
    return out or None


def _token_stem(token: str) -> str:
    return _image_stem(token)


def _agenttalk_argv(command_line: object) -> list[str] | None:
    tokens = _split_command_line(command_line)
    if not tokens:
        return None
    first = _token_stem(tokens[0])
    if first in _SHELL_HOSTS:
        return None
    if first in {"python", "python3", "py"}:
        if len(tokens) >= 3 and tokens[1] == "-m" and tokens[2] == "agenttalk":
            return tokens[3:]
        return None
    if first == "agenttalk":
        return tokens[1:]
    return None


def _option_value(tokens: list[str], index: int) -> tuple[str | None, int]:
    token = tokens[index]
    if "=" in token:
        return token.split("=", 1)[1], index + 1
    if index + 1 >= len(tokens):
        return None, len(tokens)
    return tokens[index + 1], index + 2


def _valid_launch_nonce(value: object) -> bool:
    return isinstance(value, str) and bool(_SUPERVISOR_LAUNCH_NONCE_RE.fullmatch(value))


def _has_option_token(tokens: list[str], option: str) -> bool:
    return any(arg == option or arg.startswith(option + "=") for arg in tokens)


def _agenttalk_invocation(command_line: object, root_key: str | None) -> dict | None:
    argv = _agenttalk_argv(command_line)
    if argv is None:
        return None
    root = None
    sub_i = None
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--":
            return {"root": root, "root_match": _same_root(root, root_key),
                    "subcommand": None, "args": [], "tail": argv[i + 1:]}
        if arg in _AGENTTALK_SUBCOMMANDS:
            sub_i = i
            break
        if arg == "--root" or arg.startswith("--root="):
            root, i = _option_value(argv, i)
            continue
        if arg == _SUPERVISOR_LAUNCH_NONCE_ARG or arg.startswith(
                _SUPERVISOR_LAUNCH_NONCE_ARG + "="):
            _nonce, i = _option_value(argv, i)
            continue
        i += 1
    if sub_i is None:
        return {"root": root, "root_match": _same_root(root, root_key),
                "subcommand": None, "args": [], "tail": []}
    return {
        "root": root,
        "root_match": _same_root(root, root_key),
        "subcommand": argv[sub_i],
        "args": argv[sub_i + 1:],
        "tail": [],
    }


def _parse_supervisor_launch_nonce(command_line: object) -> tuple[str | None, str | None]:
    argv = _agenttalk_argv(command_line)
    if argv is None:
        return None, "launcher_wrap_parse_failed"
    nonce = None
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--":
            if _has_option_token(argv[i + 1:], _SUPERVISOR_LAUNCH_NONCE_ARG):
                return None, "launcher_nonce_after_subcommand_or_tail"
            break
        if arg in _AGENTTALK_SUBCOMMANDS:
            if _has_option_token(argv[i + 1:], _SUPERVISOR_LAUNCH_NONCE_ARG):
                return None, "launcher_nonce_after_subcommand_or_tail"
            break
        if arg == _SUPERVISOR_LAUNCH_NONCE_ARG or arg.startswith(
                _SUPERVISOR_LAUNCH_NONCE_ARG + "="):
            value, i_next = _option_value(argv, i)
            if value is None or not _valid_launch_nonce(value):
                return None, "launcher_nonce_malformed"
            if nonce is not None:
                return None, "launcher_nonce_duplicate"
            nonce = value
            i = i_next
            continue
        i += 1
    if nonce is None:
        return None, "launcher_nonce_absent"
    return nonce, None


def parse_supervisor_launch_nonce(command_line: object) -> str | None:
    nonce, reason = _parse_supervisor_launch_nonce(command_line)
    return nonce if reason is None else None


def _agent_option(args: list[str], option: str) -> str | None:
    i = 0
    while i < len(args):
        arg = args[i]
        if arg == "--":
            return None
        if arg == option or arg.startswith(option + "="):
            value, _next = _option_value(args, i)
            return value
        i += 1
    return None


def parse_agenttalk_wait_invocation(command_line: object, root_key: str | None,
                                    agent: str) -> bool:
    inv = _agenttalk_invocation(command_line, root_key)
    if not inv or inv.get("subcommand") != "wait" or not inv.get("root_match"):
        return False
    args = inv.get("args") or []
    if _has_option_token(args, _SUPERVISOR_LAUNCH_NONCE_ARG):
        return False
    return _agent_option(args, "--for") == agent


def parse_agenttalk_wrap_invocation(command_line: object, root_key: str | None,
                                    agent: str) -> bool:
    inv = _agenttalk_invocation(command_line, root_key)
    if not inv or inv.get("subcommand") != "wrap" or not inv.get("root_match"):
        return False
    args = inv.get("args") or []
    if _has_option_token(args, _SUPERVISOR_LAUNCH_NONCE_ARG):
        return False
    agent_value = _agent_option(args, "--for")
    if agent_value != agent:
        return False
    before_tail = args[:args.index("--")] if "--" in args else args
    return "--loop" in before_tail


def _row_branch_reason(row: dict, root_key: str | None, agent: str) -> str | None:
    if _is_shell_host(row):
        return "shell_boundary"
    inv = _agenttalk_invocation(row.get("command_line"), root_key)
    if not inv:
        return None
    if inv.get("root") and not inv.get("root_match"):
        return "foreign_root_branch"
    if not inv.get("root_match"):
        return None
    sub = inv.get("subcommand")
    args = inv.get("args") or []
    if sub in {"wait", "wrap"}:
        row_agent = _agent_option(args, "--for")
        if row_agent is not None and row_agent != agent:
            return "same_root_other_agent_branch"
        if sub == "wait" and row_agent == agent:
            return None
        if sub == "wrap" and row_agent == agent and "--loop" in (
                args[:args.index("--")] if "--" in args else args):
            return None
    return "unknown_root_cli"


def _state_launcher_source(st: dict) -> dict | None:
    nonce = st.get("launcher_nonce") if isinstance(st, dict) else None
    pid = st.get("launcher_pid") if isinstance(st, dict) else None
    start = st.get("launcher_start") if isinstance(st, dict) else None
    if (
        st.get("launcher_nonce_injected") is True
        and _valid_launch_nonce(nonce)
        and isinstance(pid, int)
        and isinstance(start, str)
        and start
    ):
        return {"pid": pid, "start": start, "nonce": nonce}
    return None


