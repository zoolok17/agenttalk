"""WP-2: the agent supervisor's Python core (thin, stdlib-only, no daemon).

The supervisor itself is an EXTERNAL script the operator runs (generated by
``agenttalk supervise --init``); it owns launching/killing/relaunching agent
terminals and tracking the PIDs it launched. THIS module owns everything that
must be deterministic and CI-testable WITHOUT launching a terminal:

- :func:`build_report` - the read-only bus-side liveness snapshot
  (``agenttalk supervise --report --json``).
- :func:`plan_actions` - the SHARED decision table. Given the report, the
  supervisor's own state (launched-pid liveness + backoff + consumed restart
  ids + last-warn timestamps), and config, it returns one safe ACTION per
  agent PLUS the next state. The live loop and the ``--dry-run`` harness call
  the SAME function, so the safety table is unit-tested via fixtures and never
  depends on real process death.

Decision principle: heartbeat freshness is the liveness authority. A fresh
heartbeat is healthy even if process discovery is missing or misleading. A
stale heartbeat is recovered (best-effort kill + resume) only when the activity
hook is installed for that agent (``activity_hook``), because without it we
cannot tell "stuck" from "busy mid-long-turn" and a stale heartbeat falls back
to warn-only (``suspect_warn``, never a kill). Protected agents are never
auto-killed (warn-only). Process discovery is used only to choose scoped kill
targets for recovery.
"""

