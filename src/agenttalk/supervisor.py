# NOTE on the templates below: the DECISION lives in Python
# (`agenttalk supervise --plan`); the scripts are THIN executors that supply
# launched-pid liveness, run the plan, and do terminal mechanics. They support
# `--once --dry-run` to print the action plan without launching anything.

PS_TEMPLATE = r"""# agenttalk supervisor (PowerShell) - generated by `agenttalk supervise --init`.
# The DECISION table is in Python (`agenttalk supervise --plan`); this script
# only tracks launched PIDs, runs the plan, and launches/kills terminals.
#   .\supervisor.ps1                 # run the monitor loop
#   .\supervisor.ps1 -Once -DryRun   # print the action plan once, change nothing
param([switch]$Once, [switch]$DryRun)
$ErrorActionPreference = 'Stop'
$Root      = Split-Path -Parent $PSScriptRoot   # the project root (.agenttalk/..)
$ConfigPath = Join-Path $PSScriptRoot 'supervisor.json'
$StatePath  = Join-Path $PSScriptRoot 'supervisor-state.json'   # SCRIPT-owned, not the bus
$cfg = Get-Content $ConfigPath -Raw | ConvertFrom-Json

function Load-State {
  if (Test-Path $StatePath) { return (Get-Content $StatePath -Raw | ConvertFrom-Json) }
  return [pscustomobject]@{ agents = [pscustomobject]@{} }
}
function Save-State($state) { $state | ConvertTo-Json -Depth 8 | Set-Content $StatePath -Encoding utf8 }
function Pid-Alive($procId) {
  if (-not $procId) { return $false }
  return [bool](Get-Process -Id $procId -ErrorAction SilentlyContinue)
}
function Launch($name, $plan) {
  $a = $cfg.agents.$name
  if (-not $a.launch.windows -or $a.launch.windows -like 'EXAMPLE*') {
    Write-Warning "supervisor: agent '$name' has no real launch.windows command - fill supervisor.json"; return $null
  }
  # {SESSION_ARGS} is the planner's PS array-of-literals string (single-quoted
  # tokens - `$` does NOT expand, each token = one argument). On a FRESH Claude
  # launch the {SESSION_ID} token is still present; mint + substitute a uuid.
  # Codex has no {SESSION_ID} (it doesn't pin), so $sid stays $null there.
  $sargs = $plan.session_args_ps
  $sid = $plan.session_id
  if ($plan.launch_mode -eq 'fresh' -and $sargs -match '\{SESSION_ID\}') {
    $sid = [guid]::NewGuid().ToString()
    $sargs = $sargs -replace '\{SESSION_ID\}', $sid
  }
  $cmd = $a.launch.windows -replace '\{SESSION_ARGS\}', $sargs
  # Launch the CLI EXECUTABLE DIRECTLY (claude.cmd/codex.cmd) via Start-Process
  # -PassThru so the monitored PID dies with the agent. Do NOT wrap in
  # `powershell -NoExit -Command` or use wt.exe - both outlive the agent, so the
  # supervisor would watch the wrong PID and loop-restart forever.
  $proc = Invoke-Expression $cmd
  if ($proc -and $proc.Id) { return @{ pid = $proc.Id; session_id = $sid } }
  Write-Warning "supervisor: launch of '$name' returned no PID (need Start-Process -PassThru); not auto-restarting it"; return $null
}

do {
  $state = Load-State
  if (-not $state.agents) { $state | Add-Member agents ([pscustomobject]@{}) -Force }
  # 1) refresh launched-pid liveness into the state the planner reads
  foreach ($name in $cfg.agents.PSObject.Properties.Name) {
    $st = $state.agents.$name; if (-not $st) { $st = [pscustomobject]@{}; $state.agents | Add-Member $name $st -Force }
    $procId = $st.pid; $st | Add-Member pid_alive (Pid-Alive $procId) -Force
  }
  Save-State $state
  # 2) ask Python for the safe action plan
  $now = [int][double]::Parse((Get-Date -UFormat %s))
  $plan = (& agenttalk --root $Root supervise --plan --state-file $StatePath --now $now) | ConvertFrom-Json
  foreach ($name in $plan.agents.PSObject.Properties.Name) {
    $p = $plan.agents.$name
    if ($DryRun) { Write-Host ("{0}: {1} - {2}" -f $name, $p.action, $p.reason); continue }
    switch ($p.action) {
      { $_ -in 'relaunch','stuck_recover' } {
        # stuck_recover kills the alive-but-stuck process first; dead-relaunch
        # has nothing to kill. Both resume the pinned session.
        if ($p.kill_first -and (Pid-Alive $state.agents.$name.pid)) { Stop-Process -Id $state.agents.$name.pid -Force -ErrorAction SilentlyContinue }
        $res = Launch $name $p
        $state.agents.$name = $p.next_state    # planner fields (passes pid/session_id/launched through)
        if ($res) {
          Save-State $state
          # Apply the launch-SUCCESS state via Python (the authoritative rule:
          # Claude pins the minted session id; Codex marks launched + NO fake
          # id). Then re-load so the in-memory state matches.
          $sidArg = @(); if ($res.session_id) { $sidArg = @('--session-id', $res.session_id) }
          & agenttalk --root $Root supervise --record-launch --for $name --cli $p.cli --pid $res.pid @sidArg --state-file $StatePath | Out-Null
          $state = Load-State
          # Clear the manual marker ONLY after a CONFIRMED relaunch (a $null
          # PID = no/invalid launch command) - never silently drop a request
          # whose relaunch failed; it must remain for the next poll to retry.
          if ($p.clear_marker) { & agenttalk --root $Root supervise --clear-restart --for $name --request-id $p.clear_marker | Out-Null }
        } else {
          Write-Warning ("supervisor: {0}: {1} FAILED (no PID) - keeping marker/state for retry" -f $name, $p.action)
        }
      }
      'clear_marker' { if ($p.clear_marker) { & agenttalk --root $Root supervise --clear-restart --for $name --request-id $p.clear_marker | Out-Null }; $state.agents.$name = $p.next_state }
      'refuse_protected' { Write-Warning ("supervisor: {0}: {1}" -f $name, $p.reason); if ($p.clear_marker) { & agenttalk --root $Root supervise --clear-restart --for $name --request-id $p.clear_marker | Out-Null }; $state.agents.$name = $p.next_state }
      { $_ -in 'warn_only','suspect_warn' } {
        Write-Warning ("supervisor: {0}: {1}" -f $name, $p.reason)
        if ($p.notify -and $cfg.notify_sender -and $cfg.notify_to) {
          & agenttalk --root $Root send --from $cfg.notify_sender --to $cfg.notify_to --kind note -m ("supervisor: {0}: {1}" -f $name, $p.reason) --quiet | Out-Null
        }
        $state.agents.$name = $p.next_state
      }
      default { $state.agents.$name = $p.next_state }
    }
  }
  if (-not $DryRun) { Save-State $state }
  if (-not $Once) { Start-Sleep -Seconds ([int]$cfg.poll_seconds) }
} while (-not $Once)
"""

def init(store: Store, *, force: bool = False) -> dict:
    """Scaffold the supervisor config + PowerShell script under ``.agenttalk/``.
    Returns ``{path: "written"|"exists"}``. Never overwrites without ``force``
    (the config especially - it holds the operator's filled-in launch commands).

    v1 ships the PowerShell supervisor only (the operator is on Windows); a
    POSIX (bash) supervisor is a documented follow-up - the Python core
    (``supervise --report``/``--plan``, ``request-restart``) is already
    cross-platform, so a future ``supervisor.sh`` is a thin add.
    """
    out: dict[str, str] = {}
    # The .ps1 is written UTF-8 with a BOM (utf-8-sig): Windows PowerShell 5.1
    # decodes a BOM-less file as Windows-1252, which corrupts any non-ASCII byte
    # and cascades into parse errors (the 0.28.1 live-test bug). The template is
    # already ASCII-only; the BOM is belt-and-suspenders and is also fine for
    # PowerShell 7+. The .json stays plain UTF-8 (a BOM would break Python's
    # json.loads when the config is read back).
    targets = [
        (store.dir / "supervisor.json", CONFIG_TEMPLATE, "utf-8"),
        (store.dir / "supervisor.ps1", PS_TEMPLATE, "utf-8-sig"),
    ]
    for path, content, encoding in targets:
        if path.exists() and not force:
            out[str(path)] = "exists"
            continue
        path.write_text(content, encoding=encoding)
        out[str(path)] = "written"
    return out


# ---- activity-hook install (opt-in; unlocks stuck_recover) -----------------
#
# The hook runs `agenttalk heartbeat` on every tool call (it resolves the agent
# from $AGENTTALK_SELF and is throttled, so it's a dumb one-liner). It is what
# makes "stale heartbeat == genuinely stuck" true; until it's installed,
# activity_hook stays false and a stale heartbeat is only a warn (never a kill).

ACTIVITY_HOOK_COMMAND = "agenttalk heartbeat"


def claude_hook_snippet() -> str:
    """The PostToolUse fragment to paste into a project .claude/settings.json."""
    return json.dumps({"hooks": {"PostToolUse": [
        {"matcher": "*", "hooks": [
            {"type": "command", "command": ACTIVITY_HOOK_COMMAND}]}]}}, indent=2)


def _merge_post_tool_use_hook(settings: dict) -> bool:
    """Add the heartbeat PostToolUse hook to a settings dict IN PLACE, in the
    matcher-GROUP shape both Claude and Codex use ({"matcher","hooks":[...]}),
    preserving every existing key/group. Returns True if it changed anything
    (False = already present, idempotent). The presence-check scans the NESTED
    hooks of every group so a correctly-shaped existing hook isn't duplicated."""
    hooks = settings.setdefault("hooks", {})
    groups = hooks.setdefault("PostToolUse", [])
    if not isinstance(groups, list):
        return False  # malformed - refuse to touch
    for g in groups:
        for h in (g.get("hooks", []) if isinstance(g, dict) else []):
            if isinstance(h, dict) and h.get("command") == ACTIVITY_HOOK_COMMAND:
                return False  # already installed
    groups.append({"matcher": "*", "hooks": [
        {"type": "command", "command": ACTIVITY_HOOK_COMMAND}]})
    return True


def install_activity_hook(store: Store, *, claude: bool = True,
                          codex: bool = False) -> dict:
    """MERGE the activity-heartbeat hook into PROJECT-scoped config files -
    ``.claude/settings.json`` and/or ``.codex/hooks.json`` under the project
    root. NEVER touches global ~/.claude or ~/.codex, NEVER clobbers existing
    hooks/keys (idempotent). Returns ``{path: "installed"|"already"|"skipped"}``.
    """
    out: dict[str, str] = {}
    if claude:
        p = store.root / ".claude" / "settings.json"
        settings = {}
        if p.exists():
            try:
                settings = json.loads(p.read_text(encoding="utf-8")) or {}
            except (ValueError, OSError):
                out[str(p)] = "skipped (unreadable - merge by hand)"
                settings = None
        if settings is not None:
            changed = _merge_post_tool_use_hook(settings)
            if changed:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(json.dumps(settings, indent=2), encoding="utf-8")
            out[str(p)] = "installed" if changed else "already"
    if codex:
        # Codex uses the SAME matcher-group PostToolUse shape as Claude (a
        # flat {type,command} would mis-install and the presence-check would
        # duplicate a correctly-shaped existing hook -> a safety bug if
        # activity_hook is then trusted). .codex/hooks.json (JSON).
        p = store.root / ".codex" / "hooks.json"
        cfg = {}
        if p.exists():
            try:
                cfg = json.loads(p.read_text(encoding="utf-8")) or {}
            except (ValueError, OSError):
                out[str(p)] = "skipped (unreadable - merge by hand)"
                cfg = None
        if cfg is not None:
            changed = _merge_post_tool_use_hook(cfg)
            if changed:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(json.dumps(cfg, indent=2), encoding="utf-8")
            out[str(p)] = "installed" if changed else "already"
    return out
