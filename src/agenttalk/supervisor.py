    start = entry.get("source_launcher_start")
    nonce = entry.get("source_launcher_nonce")
    if isinstance(pid, int) and isinstance(start, str) and _valid_launch_nonce(nonce):
        return {"pid": pid, "start": start, "nonce": nonce}
    return None


