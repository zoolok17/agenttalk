def read_coordination_availability_observation(store: Store) -> tuple[dict, list[dict]]:
    """Read the bounded two-poll debounce state, failing quiet on damage."""
    path = _coordination_availability_path(store)
    if not path.exists():
        return {}, []
    try:
        if path.stat().st_size > _COORDINATION_AVAILABILITY_MAX_BYTES:
            raise ValueError("oversized")
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, json.JSONDecodeError):
        return {}, [{"code": "availability_observation_invalid"}]
    if (
        not isinstance(raw, dict)
        or frozenset(raw) != _COORDINATION_AVAILABILITY_FIELDS
        or raw.get("schema_version") != _COORDINATION_AVAILABILITY_SCHEMA
        or _event_epoch(raw.get("updated_at_epoch")) is None
    ):
        return {}, [{"code": "availability_observation_invalid"}]
    agents = raw.get("agents")
    if not isinstance(agents, dict) or len(agents) > 1024:
        return {}, [{"code": "availability_observation_invalid"}]
    clean: dict[str, dict] = {}
    problems: list[dict] = []
    for name, row in agents.items():
        invalid = (
            not isinstance(name, str)
            or _EVENT_TOKEN_RE.fullmatch(name) is None
            or not isinstance(row, dict)
            or frozenset(row) != _COORDINATION_AVAILABILITY_ROW_FIELDS
        )
        if invalid:
            if len(problems) < _COORDINATION_MAX_DIAGNOSTICS:
                problems.append({"code": "availability_observation_entry_invalid"})
            continue
        state = row.get("state")
        if state not in {
            AVAILABILITY_AVAILABLE,
            AVAILABILITY_UNAVAILABLE,
            AVAILABILITY_TERMINAL,
            AVAILABILITY_UNKNOWN,
        }:
            if len(problems) < _COORDINATION_MAX_DIAGNOSTICS:
                problems.append({"code": "availability_observation_entry_invalid"})
            continue
        consecutive = row.get("consecutive")
        first_epoch = _event_epoch(row.get("first_observed_epoch"))
        last_epoch = row.get("last_observed_epoch")
        if (
            not isinstance(row.get("subtype"), str)
            or _EVENT_TOKEN_RE.fullmatch(row["subtype"]) is None
            or not isinstance(row.get("evidence_code"), str)
            or _EVENT_TOKEN_RE.fullmatch(row["evidence_code"]) is None
            or not isinstance(consecutive, int)
            or isinstance(consecutive, bool)
            or consecutive < 1
            or first_epoch is None
            or not isinstance(last_epoch, (int, float))
            or isinstance(last_epoch, bool)
            or not math.isfinite(float(last_epoch))
            or float(last_epoch) < first_epoch
        ):
            if len(problems) < _COORDINATION_MAX_DIAGNOSTICS:
                problems.append({"code": "availability_observation_entry_invalid"})
            continue
        clean[name] = {
            "state": state,
            "subtype": row["subtype"],
            "evidence_code": row["evidence_code"],
            "consecutive": consecutive,
            "first_observed_epoch": first_epoch,
            "last_observed_epoch": float(last_epoch),
        }
    return clean, problems


def record_coordination_availability_observation(
    store: Store,
    report: dict,
    plan: dict,
    config: dict,
    *,
    now_epoch: float,
) -> None:
    """Best-effort supervisor-cadence debounce bookkeeping.

    Planning output is an input only and is never changed.  Two consecutive
    semantically identical projections are required before a detector may warn.
    """
    try:
        prior, _ = read_coordination_availability_observation(store)
        report_agents = report.get("agents") if isinstance(report.get("agents"), dict) else {}
        plan_agents = plan.get("agents") if isinstance(plan.get("agents"), dict) else {}
        config_agents = config.get("agents") if isinstance(config.get("agents"), dict) else {}
        retired = set(store.retired_agents())
        poll = config.get("poll_seconds", _DEFAULTS["poll_seconds"])
        poll = float(poll) if isinstance(poll, (int, float)) and not isinstance(poll, bool) else 15.0
        max_gap = max(5.0, poll * 3.0)
        rows: dict[str, dict] = {}
        names = set(report_agents) | set(config_agents) | retired
        for name in sorted(names):
            projection = project_coordination_availability(
                name,
                report_agents.get(name),
                plan_agents.get(name),
                config_agents.get(name),
                retired=name in retired,
            )
            old = prior.get(name) if isinstance(prior.get(name), dict) else {}
            same = all(old.get(key) == projection.get(key) for key in (
                "state", "subtype", "evidence_code"))
            last = old.get("last_observed_epoch")
            contiguous = (
                same
                and isinstance(last, (int, float))
                and 0 <= float(now_epoch) - float(last) <= max_gap
            )
            rows[name] = {
                "state": projection["state"],
                "subtype": projection["subtype"],
                "evidence_code": projection["evidence_code"],
                "consecutive": int(old.get("consecutive", 0)) + 1 if contiguous else 1,
                "first_observed_epoch": (
                    old.get("first_observed_epoch") if contiguous else float(now_epoch)
                ),
                "last_observed_epoch": float(now_epoch),
            }
        payload = {
            "schema_version": _COORDINATION_AVAILABILITY_SCHEMA,
            "updated_at_epoch": float(now_epoch),
            "agents": rows,
        }
        with store._config_lock(timeout=0.05, poll=0.01):
            _atomic_write_text(
                _coordination_availability_path(store),
                json.dumps(payload, ensure_ascii=False, sort_keys=True),
            )
    except Exception:
        return


def _restart_request_with_live_authority(store: Store, marker: dict | None) -> dict | None:
    if not isinstance(marker, dict):
        return marker
    out = dict(marker)
    authority = resolve_restart_request_authority(
        store,
        out.get("requested_by"),
        force_protected=bool(out.get("force_protected")),
        acknowledge_live_protected_kill=bool(
            out.get("acknowledge_live_protected_kill")),
    )
    out["authority_still_valid"] = (
        authority.get("authority_result") == "authorized"
        and authority.get("authorized_by") == out.get("requested_by")
    )
    out["force_protected_still_authorized"] = bool(
        authority.get("force_protected_authorized"))
    out["acknowledge_live_protected_kill_still_authorized"] = bool(
        authority.get("acknowledge_live_protected_kill_authorized"))
    out["authority_live_reason"] = authority.get("authority_reason")
    return out


def supervisor_events_path(store: Store) -> Path:
    return store.state_dir / "supervisor-events.jsonl"


def _event_now(now_epoch: float) -> str:
    return datetime.fromtimestamp(now_epoch, timezone.utc).isoformat().replace("+00:00", "Z")


def _event_token(value: object, default: str = "unknown") -> str:
    if isinstance(value, str) and _EVENT_TOKEN_RE.fullmatch(value):
        return value
    return default


def _event_bool(value: object) -> bool:
    return value is True


def _event_nonnegative_int(value: object) -> int:
    if isinstance(value, int) and not isinstance(value, bool) and value >= 0:
        return value
    return 0


def _event_epoch(value: object) -> float | None:
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        epoch = float(value)
        if math.isfinite(epoch):
            return epoch
    return None


def _decision_reason_code(plan: dict) -> str:
    explicit = _event_token(plan.get("reason_code"), "")
    if explicit:
        return explicit.lower()
    health = plan.get("health") if isinstance(plan.get("health"), dict) else {}
    warnings = health.get("warnings") if isinstance(health.get("warnings"), list) else []
    if "advisory-health-conflict" in warnings:
        return "advisory-health-conflict"
    state = _event_token(plan.get("state"), "")
    if state:
        return state.lower()
    return _event_token(plan.get("action"), "unknown").lower()


def _decision_fingerprint(agent: str, plan: dict) -> str:
    parts = [
        _event_token(agent),
        _event_token(plan.get("action")),
        _event_token(plan.get("state")),
        _decision_reason_code(plan),
        "notify" if plan.get("notify") is True else "silent",
        "clear" if isinstance(plan.get("clear_marker"), str) else "keep",
    ]
    return "|".join(parts)


def _stored_decision_fingerprint(event: dict) -> str:
    parts = [
        _event_token(event.get("agent")),
        _event_token(event.get("action")),
        _event_token(event.get("state")),
        _event_token(event.get("reason_code")),
        "notify" if event.get("notify") is True else "silent",
        "clear" if event.get("clear_marker") is True else "keep",
    ]
    return "|".join(parts)


def _sanitize_agent_decision_event(obj: dict) -> dict:
    event: dict[str, object] = {
        "schema_version": 1,
        "kind": "agent_decision",
        "at": _event_token(obj.get("at")),
        "agent": _event_token(obj.get("agent")),
        "action": _event_token(obj.get("action")),
        "state": _event_token(obj.get("state")),
        "reason_code": _event_token(obj.get("reason_code")),
        "notify": _event_bool(obj.get("notify")),
        "clear_marker": _event_bool(obj.get("clear_marker")),
    }
    at_epoch = _event_epoch(obj.get("at_epoch"))
    if at_epoch is not None:
        event["at_epoch"] = at_epoch
    event["fingerprint"] = _stored_decision_fingerprint(event)
    return event


def _sanitize_summary_states(value: object) -> dict[str, int]:
    if not isinstance(value, dict):
        return {}
    states: dict[str, int] = {}
    for raw_state, raw_count in value.items():
        state = _event_token(raw_state)
        states[state] = states.get(state, 0) + _event_nonnegative_int(raw_count)
    return states


def _sanitize_poll_summary_event(obj: dict) -> dict:
    event: dict[str, object] = {
        "schema_version": 1,
        "kind": "poll_summary",
        "at": _event_token(obj.get("at")),
        "planned_agents": _event_nonnegative_int(obj.get("planned_agents")),
        "healthy_idle": _event_nonnegative_int(obj.get("healthy_idle")),
        "states": _sanitize_summary_states(obj.get("states")),
    }
    at_epoch = _event_epoch(obj.get("at_epoch"))
    if at_epoch is not None:
        event["at_epoch"] = at_epoch
    return event


def _sanitize_supervisor_event(obj: dict) -> dict | None:
    kind = _event_token(obj.get("kind"), "")
    if kind == "agent_decision":
        return _sanitize_agent_decision_event(obj)
    if kind == "poll_summary":
        return _sanitize_poll_summary_event(obj)
    return None


def read_supervisor_events(store: Store, *, limit: int | None = None) -> tuple[list[dict], list[str]]:
    """Read the supervisor decision-event ring fail-safe.

    The reader tails a fixed byte budget before JSON parsing, so even an externally
    bloated file cannot make status/supervisor reads scan unbounded history. Rows
    are normalized to the known token-only event schemas before any caller sees or
    uses them, so a pre-existing polluted ring cannot leak free text through reads.
    """
    path = supervisor_events_path(store)
    if not path.exists():
        return [], []
    warnings: list[str] = []
    try:
        with path.open("rb") as f:
            f.seek(0, 2)
            size = f.tell()
            if size > SUPERVISOR_EVENT_TAIL_BYTES:
                f.seek(-SUPERVISOR_EVENT_TAIL_BYTES, 2)
                warnings.append("supervisor_events_tail_truncated")
            else:
                f.seek(0)
            raw = f.read()
    except OSError as exc:
        return [], [f"supervisor_events_unreadable:{type(exc).__name__}"]
    text = raw.decode("utf-8", "replace")
    lines = text.splitlines()
    if warnings and lines:
        lines = lines[1:]  # likely a partial first line after a tail seek
    events: list[dict] = []
    for idx, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            warnings.append(f"supervisor_events_torn:{idx}")
            continue
        if not isinstance(obj, dict):
            warnings.append(f"supervisor_events_malformed:{idx}")
            continue
        event = _sanitize_supervisor_event(obj)
        if event is None:
            warnings.append(f"supervisor_events_malformed:{idx}")
            continue
        if event != obj:
            warnings.append(f"supervisor_events_sanitized:{idx}")
        events.append(event)
    if isinstance(limit, int) and limit >= 0:
        events = events[-limit:] if limit else []
    return events, warnings


def append_supervisor_events(store: Store, events: list[dict], *,
                             cap: int = SUPERVISOR_EVENT_RING_CAP) -> None:
    """Best-effort bounded JSONL append implemented as read/cap/rewrite."""
    if not events:
        return
    clean_events: list[dict] = []
    for event in events:
        if not isinstance(event, dict):
            continue
        clean = _sanitize_supervisor_event(event)
        if clean is not None:
            clean_events.append(clean)
    if not clean_events:
        return
    cap = cap if isinstance(cap, int) and cap > 0 else SUPERVISOR_EVENT_RING_CAP
    try:
        with store._config_lock(timeout=0.05, poll=0.01):
            prior, _ = read_supervisor_events(store)
            kept = [*prior, *clean_events][-cap:]
            path = supervisor_events_path(store)
            path.parent.mkdir(parents=True, exist_ok=True)
            text = "".join(
                json.dumps(e, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n"
                for e in kept
            )
            _atomic_write_text(path, text)
    except Exception:
        return


def _decision_event(agent: str, plan: dict, *, now_epoch: float) -> dict:
    fingerprint = _decision_fingerprint(agent, plan)
    return {
        "schema_version": 1,
        "kind": "agent_decision",
        "at": _event_now(now_epoch),
        "at_epoch": float(now_epoch),
        "agent": _event_token(agent),
        "action": _event_token(plan.get("action")),
        "state": _event_token(plan.get("state")),
        "reason_code": _decision_reason_code(plan),
        "notify": plan.get("notify") is True,
        "clear_marker": isinstance(plan.get("clear_marker"), str),
        "fingerprint": fingerprint,
    }


def _summary_event(plan: dict, *, now_epoch: float) -> dict:
    agents = plan.get("agents") if isinstance(plan.get("agents"), dict) else {}
    states: dict[str, int] = {}
    healthy = 0
    for p in agents.values():
        if not isinstance(p, dict):
            continue
        state = _event_token(p.get("state"))
        states[state] = states.get(state, 0) + 1
        if state == "HEALTHY_IDLE":
            healthy += 1
    return {
        "schema_version": 1,
        "kind": "poll_summary",
        "at": _event_now(now_epoch),
        "at_epoch": float(now_epoch),
        "planned_agents": len(agents),
        "healthy_idle": healthy,
        "states": states,
    }


def record_supervisor_plan_events(store: Store, plan: dict, *,
                                  now_epoch: float,
                                  cap: int = SUPERVISOR_EVENT_RING_CAP,
                                  summary_interval_seconds: float =
                                  SUPERVISOR_EVENT_SUMMARY_INTERVAL_SECONDS) -> None:
    """Append redacted supervisor decision events once per transition.

    Events contain planner tokens only: action, state, booleans, and bounded
    reason codes. Free-form plan reasons, restart reasons, command lines, and
    config-blocked summaries are deliberately not representable.
    """
    try:
        agents = plan.get("agents") if isinstance(plan.get("agents"), dict) else {}
        prior, _ = read_supervisor_events(store)
        last_fp: dict[str, str] = {}
        last_summary_epoch: float | None = None
        for event in prior:
            if event.get("kind") == "agent_decision":
                if event.get("action") == _LAUNCH_BARRIER_ACTION:
                    continue
                agent = event.get("agent")
                fp = event.get("fingerprint")
                if isinstance(agent, str) and isinstance(fp, str):
                    last_fp[agent] = fp
            elif event.get("kind") == "poll_summary":
                ts = event.get("at_epoch")
                if isinstance(ts, (int, float)):
                    last_summary_epoch = float(ts)
        new_events: list[dict] = []
        for agent in sorted(agents):
            p = agents.get(agent)
            if not isinstance(p, dict):
                continue
            fp = _decision_fingerprint(agent, p)
            if last_fp.get(agent) != fp:
                new_events.append(_decision_event(agent, p, now_epoch=now_epoch))
        if (last_summary_epoch is None
                or now_epoch - last_summary_epoch >= float(summary_interval_seconds)):
            new_events.append(_summary_event(plan, now_epoch=now_epoch))
        append_supervisor_events(store, new_events, cap=cap)
    except Exception:
        return


def record_supervisor_launch_barrier_event(store: Store, agent: str, *,
                                           reason_code: str, now_epoch: float,
                                           cap: int = SUPERVISOR_EVENT_RING_CAP) -> None:
    """Append a deduped post-kill launch-barrier decision event.

    The generated executor records the normal plan first, then this only when a
    fresh post-kill snapshot refuses launch. Dedupe is against the last agent
    decision fingerprint, so a steady barrier does not flood the ring.
    """
    try:
        plan = {
            "action": _LAUNCH_BARRIER_ACTION,
            "state": "LAUNCH_BLOCKED",
            "reason_code": reason_code,
            "notify": True,
        }
        fp = _decision_fingerprint(agent, plan)
        prior, _ = read_supervisor_events(store)
        for event in reversed(prior):
            if event.get("kind") == "agent_decision" and event.get("agent") == _event_token(agent):
                if event.get("action") != _LAUNCH_BARRIER_ACTION:
                    continue
                if event.get("fingerprint") == fp:
                    return
                break
        append_supervisor_events(store, [_decision_event(agent, plan, now_epoch=now_epoch)], cap=cap)
    except Exception:
        return


def _coordination_barrier_path(store: Store, agent: str) -> Path:
    return store.state_dir / _COORDINATION_BARRIER_DIR / f"{validate_agent_name(agent)}.json"


def read_coordination_barrier_observations(store: Store) -> tuple[list[dict], list[dict]]:
    """Read strict manual-restart barrier observations, skipping damaged rows."""
    root = store.state_dir / _COORDINATION_BARRIER_DIR
    if not root.is_dir():
        return [], []
    rows: list[dict] = []
    problems: list[dict] = []
    paths = []
    for index, path in enumerate(root.glob("*.json")):
        if index >= 256:
            problems.append({"code": "restart_barrier_observation_limit_reached"})
            break
        paths.append(path)
    for path in sorted(paths):
        try:
            if path.stat().st_size > _COORDINATION_BARRIER_MAX_BYTES:
                raise ValueError("oversized")
            raw = json.loads(path.read_text(encoding="utf-8"))
            if (
                not isinstance(raw, dict)
                or frozenset(raw) != _COORDINATION_BARRIER_FIELDS
                or raw.get("schema_version") != _COORDINATION_BARRIER_SCHEMA
            ):
                raise ValueError("schema")
            agent = validate_agent_name(raw.get("agent"))
            request_id = raw.get("request_id")
            fingerprint = raw.get("survivor_fingerprint")
            if (
                path.stem != agent
                or not isinstance(request_id, str)
                or _EVENT_TOKEN_RE.fullmatch(request_id) is None
                or not isinstance(fingerprint, str)
                or re.fullmatch(r"[0-9a-f]{64}", fingerprint) is None
                or raw.get("blocked") is not True
                or not isinstance(raw.get("barrier_reason"), str)
                or _EVENT_TOKEN_RE.fullmatch(raw["barrier_reason"]) is None
            ):
                raise ValueError("identity")
            marker_epoch = _event_epoch(raw.get("marker_epoch"))
            first_epoch = _event_epoch(raw.get("first_observed_epoch"))
            last_epoch = _event_epoch(raw.get("last_observed_epoch"))
            consecutive = raw.get("consecutive_blocked_polls")
            if (
                marker_epoch is None
                or first_epoch is None
                or last_epoch is None
                or not isinstance(consecutive, int)
                or isinstance(consecutive, bool)
                or consecutive < 1
                or first_epoch < marker_epoch
                or last_epoch < first_epoch
            ):
                raise ValueError("timing")
            rows.append({
                "schema_version": _COORDINATION_BARRIER_SCHEMA,
                "agent": agent,
                "request_id": request_id,
                "marker_epoch": marker_epoch,
                "barrier_reason": raw["barrier_reason"],
                "survivor_fingerprint": fingerprint,
                "blocked": True,
                "first_observed_epoch": first_epoch,
                "last_observed_epoch": last_epoch,
                "consecutive_blocked_polls": consecutive,
            })
        except (OSError, TypeError, ValueError, json.JSONDecodeError):
            if len(problems) < _COORDINATION_MAX_DIAGNOSTICS:
                problems.append({
                    "code": "restart_barrier_observation_invalid",
                    "path": path.name,
                })
    return rows, problems


def record_supervisor_launch_barrier_observation(
    store: Store,
    agent: str,
    barrier: dict,
    *,
    now_epoch: float,
) -> None:
    """Record or clear the observational two-poll manual-restart barrier state.

    Only a current manual restart marker can create state.  Automatic stale
    recovery has no request id and is intentionally excluded.  A clear barrier
    deletes the observation; the detector independently re-checks the live
    marker id/epoch before projecting anything.
    """
    try:
        path = _coordination_barrier_path(store, agent)
        with store._config_lock(timeout=0.05, poll=0.01):
            if not isinstance(barrier, dict) or barrier.get("blocked") is not True:
                try:
                    path.unlink()
                except FileNotFoundError:
                    pass
                return
            marker = store.read_restart_request(agent)
            if not isinstance(marker, dict) or marker.get("source") != "manual":
                return
            request_id = marker.get("request_id")
            marker_epoch = _event_epoch(marker.get("at_epoch"))
            if (
                not isinstance(request_id, str)
                or _EVENT_TOKEN_RE.fullmatch(request_id) is None
                or marker_epoch is None
            ):
                return
            survivors = []
            raw_survivors = barrier.get("survivors")
            if isinstance(raw_survivors, list):
                for row in raw_survivors[:8]:
                    if not isinstance(row, dict):
                        continue
                    survivors.append({
                        "kind": _event_token(row.get("kind")),
                        "pid": row.get("pid") if isinstance(row.get("pid"), int) else None,
                        "name": _event_token(row.get("name")),
                    })
            survivors.sort(key=lambda row: (row["kind"], row["pid"] or -1, row["name"]))
            reason = _event_token(barrier.get("reason"))
            fingerprint = hashlib.sha256(json.dumps(
                {"reason": reason, "survivors": survivors},
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")).hexdigest()
            prior_rows, _ = read_coordination_barrier_observations(store)
            prior = next((row for row in prior_rows if row.get("agent") == agent), None)
            same = (
                isinstance(prior, dict)
                and prior.get("request_id") == request_id
                and prior.get("marker_epoch") == marker_epoch
                and prior.get("survivor_fingerprint") == fingerprint
                and float(now_epoch) >= float(prior.get("last_observed_epoch", now_epoch))
            )
            payload = {
                "schema_version": _COORDINATION_BARRIER_SCHEMA,
                "agent": agent,
                "request_id": request_id,
                "marker_epoch": marker_epoch,
                "barrier_reason": reason,
                "survivor_fingerprint": fingerprint,
                "blocked": True,
                "first_observed_epoch": (
                    prior.get("first_observed_epoch") if same else float(now_epoch)
                ),
                "last_observed_epoch": float(now_epoch),
                "consecutive_blocked_polls": (
                    int(prior.get("consecutive_blocked_polls", 0)) + 1 if same else 1
                ),
            }
            path.parent.mkdir(parents=True, exist_ok=True)
            _atomic_write_text(path, json.dumps(payload, ensure_ascii=False, sort_keys=True))
    except Exception:
        return


def lead_liveness_from_bus(*, agent: str, role: str | None, operator_facing: str | None,
                           heartbeat_age_seconds: object, heartbeat_stale: object,
                           waiting: object, health_reason_code: object = None,
                           stale_after_seconds: float =
                           LEAD_LIVENESS_STALE_AFTER_SECONDS) -> dict | None:
    """Display-only liveness for interactive leads without wrapper health."""
    _ = role, heartbeat_stale
    if agent != operator_facing or health_reason_code != "health_missing":
        return None
    age = heartbeat_age_seconds
    stale_after = (
        float(stale_after_seconds)
        if isinstance(stale_after_seconds, (int, float)) and stale_after_seconds >= 0
        else LEAD_LIVENESS_STALE_AFTER_SECONDS
    )
    if isinstance(age, (int, float)) and math.isfinite(float(age)) and float(age) <= stale_after:
        return {
            "state": "idle_waiting" if waiting else "active",
            "source": "bus_last_seen",
            "last_seen_seconds": round(float(age), 3),
            "stale_after_seconds": stale_after,
            "advisory": True,
        }
    return {
        "state": "unknown",
        "source": "bus_last_seen",
        "last_seen_seconds": (
            round(float(age), 3)
            if isinstance(age, (int, float)) and math.isfinite(float(age)) else None
        ),
        "stale_after_seconds": stale_after,
        "advisory": True,
    }


def _assessment_health(rpt: dict, lead_liveness: dict | None) -> dict:
    health = rpt.get("health") if isinstance(rpt.get("health"), dict) else {}
    state = health_model.label(health)
    reason = health.get("reason_code") if isinstance(health.get("reason_code"), str) else None
    effective = state
    if (state == health_model.STATE_UNKNOWN and reason == "health_missing"
            and isinstance(lead_liveness, dict)):
        ll_state = lead_liveness.get("state")
        if isinstance(ll_state, str) and ll_state != "unknown":
            effective = ll_state
    return {
        "state": state,
        "effective_state": effective,
        "reason_code": reason,
        "age_seconds": health.get("age_seconds") if isinstance(
            health.get("age_seconds"), (int, float)) else None,
        "warnings": health.get("warnings") if isinstance(health.get("warnings"), list) else [],
        "advisory": True,
    }


def supervisor_agent_assessment(name: str, rpt: dict, plan: dict | None, *,
                                operator_facing: str | None = None,
                                lead_liveness_stale_after_seconds: float =
                                LEAD_LIVENESS_STALE_AFTER_SECONDS) -> dict:
    health = rpt.get("health") if isinstance(rpt.get("health"), dict) else {}
    lead_liveness = lead_liveness_from_bus(
        agent=name,
        role=rpt.get("role") if isinstance(rpt.get("role"), str) else None,
        operator_facing=operator_facing,
        heartbeat_age_seconds=rpt.get("heartbeat_age_seconds"),
        heartbeat_stale=rpt.get("heartbeat_stale"),
        waiting=rpt.get("waiting"),
        health_reason_code=health.get("reason_code"),
        stale_after_seconds=lead_liveness_stale_after_seconds,
    )
    decision = None
    if isinstance(plan, dict):
        decision = {
            "action": plan.get("action"),
            "state": plan.get("state"),
            "reason": plan.get("reason"),
        }
        if isinstance(plan.get("health"), dict):
            decision["health"] = plan["health"]
    rr = rpt.get("restart_request") if isinstance(rpt.get("restart_request"), dict) else None
    hold = rpt.get("config_blocked_hold") if isinstance(
        rpt.get("config_blocked_hold"), dict) else None
    return {
        "name": name,
        "role": rpt.get("role"),
        "protected": bool(rpt.get("protected")),
        "heartbeat_stale": bool(rpt.get("heartbeat_stale")),
        "heartbeat_age_seconds": rpt.get("heartbeat_age_seconds"),
        "stuck_after_seconds": rpt.get("stuck_after_seconds"),
        "health": _assessment_health(rpt, lead_liveness),
        "lead_liveness": lead_liveness,
        "waiting": {
            "present": bool(rpt.get("waiting")),
            "pid": rpt.get("waiting_pid"),
            "pid_alive": bool(rpt.get("waiting_pid_alive")),
            "deadline_epoch": rpt.get("waiting_deadline_epoch"),
        },
        "restart_request": {
            "pending": rr is not None,
            "request_id": rr.get("request_id") if rr else None,
            "requested_by": rr.get("requested_by") if rr else None,
        },
        "config_blocked_hold": {
            "present": hold is not None,
            "summary_code": "config_blocked" if hold is not None else None,
        },
        "session_id": rpt.get("session_id"),
        "lead_loop": rpt.get("lead_loop") if isinstance(rpt.get("lead_loop"), dict) else None,
        "lead_loop_exit": (
            rpt.get("lead_loop_exit") if isinstance(rpt.get("lead_loop_exit"), dict) else None
        ),
        "decision": decision,
    }


def _redacted_observation_value(value: object) -> object:
    if value is None or isinstance(value, bool):
        return value
    if isinstance(value, int) and not isinstance(value, bool):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, str):
        return _event_token(value, "redacted")
    if isinstance(value, list):
        return [_redacted_observation_value(item) for item in value]
    if isinstance(value, dict):
        out: dict[str, object] = {}
        for key, item in value.items():
            safe_key = _event_token(key, "redacted")
            out[safe_key] = _redacted_observation_value(item)
        return out
    return None


def _redacted_restart_request(marker: object) -> dict | None:
    if not isinstance(marker, dict):
        return None
    out: dict[str, object] = {}
    for key in (
        "request_id",
        "requested_by",
        "force_protected",
        "live_ack",
        "authority_live",
        "authority_reason",
        "authority_live_reason",
    ):
        if key in marker:
            out[key] = _redacted_observation_value(marker.get(key))
    return out


