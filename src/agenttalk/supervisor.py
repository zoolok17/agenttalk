def build_supervisor_observation(store: Store, *, now_epoch: float,
                                 state: dict | None = None,
                                 supervisor_config: dict | None = None,
                                 snapshot: list[dict] | None = None,
                                 event_limit: int = 20,
                                 lead_liveness_stale_after_seconds: float =
                                 LEAD_LIVENESS_STALE_AFTER_SECONDS) -> dict:
    """Read-only operator view: report + exact planner output + bounded ring tail."""
    config = supervisor_config if isinstance(supervisor_config, dict) else {}
    stuck = config.get("stuck_after_seconds")
    stuck = float(stuck) if isinstance(stuck, (int, float)) else None
    state = state if isinstance(state, dict) else {}
    report = build_report(
        store,
        now_epoch=now_epoch,
        stuck_after_seconds=stuck,
        state=state,
        supervisor_config=config,
    )
    plan = plan_actions(report, state, config, now_epoch=now_epoch, snapshot=snapshot)
    events, event_warnings = read_supervisor_events(store, limit=event_limit)
    agents = []
    rpt_agents = report.get("agents") if isinstance(report.get("agents"), dict) else {}
    plan_agents = plan.get("agents") if isinstance(plan.get("agents"), dict) else {}
    for name in report.get("roster", []):
        rpt = rpt_agents.get(name)
        if not isinstance(rpt, dict):
            continue
        agents.append(supervisor_agent_assessment(
            name, rpt, plan_agents.get(name), operator_facing=report.get("operator_facing"),
            lead_liveness_stale_after_seconds=lead_liveness_stale_after_seconds))
    return {
        "schema_version": 1,
        "root": str(store.root),
        "now_epoch": float(now_epoch),
        "now": _event_now(now_epoch),
        "event_ring": {
            "path": str(supervisor_events_path(store)),
            "cap": SUPERVISOR_EVENT_RING_CAP,
            "events": events,
            "warnings": event_warnings,
        },
        "agents": agents,
        "report": _redacted_observation_report(report),
        "plan": _redacted_observation_plan(plan),
    }

# Per-CLI session-argument templates, as LISTS of literal tokens (so the
# generated PowerShell uses an array-of-literals ArgumentList - single-quoted
# PS literals do NOT expand `$`, so the Codex `$agenttalk-listen` prompt and
# any token survive intact, sidestepping the quote-nesting + $-expansion
# hazards codex flagged). The launch PROMPT is the EXPLICIT listen skill for
# BOTH fresh and resume (a fresh session has no context, so prose won't enter
# listen mode): Claude `/agenttalk.listen`, Codex `$agenttalk-listen`.
# {SESSION_ID} is filled by Python for resume, or by the script (claude only)
# after it mints a uuid. Operator-overridable per agent via
# config["agents"][n]["session"]["fresh"|"resume"] (a token list).
_SESSION_DEFAULTS = {
    "claude": {
        # {PERM_MODE} is filled from claude_permission_mode (default
        # "bypassPermissions"): an UNATTENDED supervised agent must NEVER prompt
        # (no human to answer) and must NOT auto-deny real work. Set on BOTH fresh
        # AND resume - the mode is not persisted across sessions, so a fresh
        # launch with no mode would default to prompting and HANG (codex +
        # claude-code-guide converged ruling, 0.28.1 blocker #2).
        "fresh": ["--session-id", "{SESSION_ID}", "--permission-mode", "{PERM_MODE}",
                  "-p", "/agenttalk.listen"],
        "resume": ["--resume", "{SESSION_ID}", "--permission-mode", "{PERM_MODE}",
                   "--allowedTools", "Bash(agenttalk *)", "-p", "/agenttalk.listen"],
    },
    "codex": {
        # Codex does NOT pin a session id at launch; a fresh launch starts with
        # the listen skill, a relaunch RESUMES the most-recent workspace session
        # (`resume --last`, documented best-effort). The skill is ALWAYS present.
        "fresh": ["-a", "never", "-s", "workspace-write", "$agenttalk-listen"],
        "resume": ["resume", "--last", "-a", "never", "-s", "workspace-write",
                   "$agenttalk-listen"],
    },
}


def _backoff_cfg(config: dict) -> dict:
    b = dict(_DEFAULTS["backoff"])
    raw = config.get("backoff") if isinstance(config.get("backoff"), dict) else {}
    for k in b:
        if isinstance(raw.get(k), (int, float)):
            b[k] = raw[k]
