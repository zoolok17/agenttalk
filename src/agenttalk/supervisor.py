def _prior_valid(entry: dict, *, root_key: str | None, agent: str,
                 request_id: str | None, now_epoch: float,
                 st: dict, diagnostics: dict[str, int]) -> bool:
    required = (
        "attribution_model",
        "root_key",
        "agent",
        "request_id",
        "pid",
        "start",
        "source",
        "captured_at_epoch",
        "last_fresh_attribution_epoch",
    )
    if any(key not in entry for key in required):
        _bump(diagnostics, "prior_field_missing")
        return False
    if entry.get("attribution_model") != _ATTRIBUTION_MODEL:
        _bump(diagnostics, "prior_field_missing")
        return False
    if entry.get("root_key") != root_key or entry.get("agent") != agent:
        _bump(diagnostics, "prior_field_missing")
        return False
    if entry.get("request_id") != request_id:
        _bump(diagnostics, "prior_request_mismatch")
        return False
    if not isinstance(entry.get("pid"), int):
        _bump(diagnostics, "prior_field_missing")
        return False
    if not isinstance(entry.get("start"), str) or not entry.get("start"):
        _bump(diagnostics, "prior_field_missing")
        return False
    last = entry.get("last_fresh_attribution_epoch")
    if not isinstance(last, (int, float)) or isinstance(last, bool):
        _bump(diagnostics, "prior_field_missing")
        return False
    if now_epoch - float(last) > _PROVENANCE_TTL_SECONDS:
        _bump(diagnostics, "prior_ttl_expired")
        return False
    if (
        entry.get("source") in _LAUNCHER_DERIVED_PRIOR_SOURCES
        or "source_launcher_nonce" in entry
        or "source_launcher_pid" in entry
        or "source_launcher_start" in entry
    ):
        entry_source = _entry_launcher_source(entry)
        state_source = _state_launcher_source(st)
        if entry_source is None:
            _bump(diagnostics, "prior_field_missing")
            return False
        if state_source is None:
            if (
                st.get("launcher_nonce_injected") is False
                and st.get("launcher_nonce_missing_reason") == "unsupported_launch_argv"
            ):
                _bump(diagnostics, "launcher_nonce_unsupported_argv")
            else:
                _bump(diagnostics, "launcher_nonce_missing_state")
            return False
        if entry_source != state_source:
            _bump(diagnostics, "launcher_nonce_mismatch")
            return False
    return True


def _usable_priors(raw: object, *, root_key: str | None, agent: str,
                   request_id: str | None, now_epoch: float,
                   st: dict, diagnostics: dict[str, int]) -> tuple[list[dict], list[dict]]:
    if raw is None:
        return [], []
    if not isinstance(raw, list):
        _bump(diagnostics, "torn_provenance_read")
        return [], []
    valid: list[dict] = []
    legacy: list[dict] = []
    for item in raw:
        if not isinstance(item, dict):
            _bump(diagnostics, "torn_provenance_read")
            continue
        if item.get("attribution_model") == _ATTRIBUTION_MODEL:
            if _prior_valid(item, root_key=root_key, agent=agent,
                            request_id=request_id, now_epoch=now_epoch,
                            st=st, diagnostics=diagnostics):
                valid.append(item)
        else:
            legacy.append(item)
    return valid, legacy


def _children_map(idx: dict[int, dict]) -> dict[int, list[int]]:
    kids: dict[int, list[int]] = {}
    for pid, row in idx.items():
        ppid = row.get("parent_pid")
        if isinstance(ppid, int):
            kids.setdefault(ppid, []).append(pid)
    return kids


def _strict_child_edge(parent: dict, child: dict, *,
                       root_key: str | None, agent: str,
                       diagnostics: dict[str, int]) -> bool:
    if child.get("parent_pid") != parent.get("pid"):
        return False
    branch = _row_branch_reason(child, root_key, agent)
    if branch is not None:
        _bump(diagnostics, branch)
        return False
    parent_epoch = _iso_epoch(_start_of(parent))
    child_epoch = _iso_epoch(_start_of(child))
    if parent_epoch is None or child_epoch is None:
        _bump(diagnostics, "unparseable_start_edge")
        return False
    if child_epoch == parent_epoch:
        _bump(diagnostics, "equal_start_edge")
        return False
    if child_epoch < parent_epoch:
        _bump(diagnostics, "inverted_start_edge")
        return False
    return True


def _root_wait_brain(idx: dict[int, dict], wait_row: dict, cfg_agent: dict,
                     root_key: str | None, agent: str,
                     diagnostics: dict[str, int]) -> dict | None:
    child = wait_row
    best = None
    seen: set[int] = set()
    while True:
        ppid = child.get("parent_pid")
        parent = idx.get(ppid) if isinstance(ppid, int) else None
        if not isinstance(parent, dict):
            return best
        pid = parent.get("pid")
        if not isinstance(pid, int) or pid in seen:
            return best
        seen.add(pid)
        branch = _row_branch_reason(parent, root_key, agent)
        if branch is not None:
            _bump(diagnostics, branch)
            return best
        parent_epoch = _iso_epoch(_start_of(parent))
        child_epoch = _iso_epoch(_start_of(child))
        if parent_epoch is None or child_epoch is None:
            _bump(diagnostics, "unparseable_start_edge")
            return best
        if parent_epoch == child_epoch:
            _bump(diagnostics, "equal_start_edge")
            return best
        if parent_epoch > child_epoch:
            _bump(diagnostics, "inverted_start_edge")
            return best
        if _is_expected_seed_row(parent, cfg_agent, agent, root_key):
            best = parent
        child = parent


def _attribution(
    snapshot: list[dict] | None,
    st: dict,
    cfg_agent: dict,
    agent: str,
    *,
    root_key: str | None,
    request_id: str | None,
    now_epoch: float,
) -> dict:
    diagnostics = _diag()
    prior_raw = st.get("managed_pids") if isinstance(st, dict) else None
    valid_priors, legacy_priors = _usable_priors(
        prior_raw,
        root_key=root_key,
        agent=agent,
        request_id=request_id,
        now_epoch=now_epoch,
        st=st,
        diagnostics=diagnostics,
    )
    if snapshot is None:
        _bump(diagnostics, "snapshot_unavailable_no_descendants")
        for _legacy in legacy_priors:
            _bump(diagnostics, "legacy_unverifiable_dropped")
        targets = []
        for entry in valid_priors:
            targets.append({
                "pid": entry["pid"],
                "start": entry["start"],
                "reason": "provenanced_prior",
                "source": "provenanced_prior",
                "seed_descendants": False,
            })
        return {
            "snapshot_available": False,
            "targets": targets,
            "managed_pids": valid_priors,
            "diagnostics": diagnostics,
            "brain_pid": st.get("brain_pid"),
            "brain_start": st.get("brain_start"),
            "wait_alive": False,
            "discovered_brain": False,
        }

    idx = _snap_index(snapshot)
    kids = _children_map(idx)
    targets_by_pid: dict[int, dict] = {}
    seed_pids: set[int] = set()
    seed_launcher_sources: dict[int, dict] = {}
    launcher_pid = st.get("launcher_pid")
    launcher_start = st.get("launcher_start")
    launcher_row = idx.get(launcher_pid) if isinstance(launcher_pid, int) else None
    launcher_mismatch = (
        isinstance(launcher_pid, int)
        and isinstance(launcher_row, dict)
        and isinstance(launcher_start, str)
        and launcher_start
        and _start_of(launcher_row) != launcher_start
    )
    confirmed_launcher = False
    launcher_source = None
    if launcher_mismatch:
        _bump(diagnostics, "pid_reuse_suppressed")
    if isinstance(launcher_row, dict):
        confirmed_launcher, launcher_source = _is_confirmed_launcher(
            idx, launcher_row, st, root_key, agent, diagnostics)
    if confirmed_launcher:
        confirmed_launcher = True
        _record_target(targets_by_pid, launcher_row, "confirmed_launcher",
                       seed_descendants=True, launcher_source=launcher_source)
        seed_pids.add(launcher_pid)
        if isinstance(launcher_pid, int) and launcher_source is not None:
            seed_launcher_sources[launcher_pid] = launcher_source

    own_wait_rows: list[dict] = []
    for row in idx.values():
        pid = row.get("pid")
        if not isinstance(pid, int):
            continue
        if isinstance(launcher_pid, int) and pid == launcher_pid:
            continue
        branch = _row_branch_reason(row, root_key, agent)
        if branch is not None:
            _bump(diagnostics, branch)
            continue
        if parse_agenttalk_wrap_invocation(row.get("command_line"), root_key, agent):
            _record_target(targets_by_pid, row, "own_wrapper", seed_descendants=True)
            seed_pids.add(pid)
        elif parse_agenttalk_wait_invocation(row.get("command_line"), root_key, agent):
            _record_target(targets_by_pid, row, "own_wait", seed_descendants=False)
            own_wait_rows.append(row)

    brain_row = None
    for wait_row in own_wait_rows:
        cand = _root_wait_brain(idx, wait_row, cfg_agent, root_key, agent, diagnostics)
        if cand is None:
            continue
        if brain_row is None:
            brain_row = cand
        else:
            cand_epoch = _iso_epoch(_start_of(cand)) or float("-inf")
            brain_epoch = _iso_epoch(_start_of(brain_row)) or float("-inf")
            if cand_epoch < brain_epoch:
                brain_row = cand
    if brain_row is not None:
        _record_target(targets_by_pid, brain_row, "root_wait_brain",
                       seed_descendants=True)
        if isinstance(brain_row.get("pid"), int):
            seed_pids.add(brain_row["pid"])

    for entry in valid_priors:
        if entry.get("pid") == launcher_pid:
            continue
        row = idx.get(entry.get("pid"))
        if not isinstance(row, dict) or _start_of(row) != entry.get("start"):
            continue
        if entry["pid"] in targets_by_pid:
            continue
        reason = str(entry.get("source") or "provenanced_prior")
        _record_target(
            targets_by_pid,
            row,
            reason,
            seed_descendants=bool(entry.get("seed_descendants")),
            launcher_source=_entry_launcher_source(entry),
        )
        if entry["pid"] in targets_by_pid:
            targets_by_pid[entry["pid"]]["prior_only"] = True
        if entry.get("seed_descendants") and isinstance(entry.get("pid"), int):
            seed_pids.add(entry["pid"])
            prior_source = _entry_launcher_source(entry)
            if prior_source is not None:
                seed_launcher_sources[entry["pid"]] = prior_source

    queue = list(seed_pids)
    visited_seed: set[int] = set()
    while queue:
        parent_pid = queue.pop(0)
        if parent_pid in visited_seed:
            continue
        visited_seed.add(parent_pid)
        parent = idx.get(parent_pid)
        if not isinstance(parent, dict):
            continue
        for child_pid in kids.get(parent_pid, []):
            if child_pid in targets_by_pid:
                continue
            child = idx.get(child_pid)
            if not isinstance(child, dict):
                continue
            if not _strict_child_edge(parent, child, root_key=root_key,
                                      agent=agent, diagnostics=diagnostics):
                continue
            child_launcher_source = seed_launcher_sources.get(parent_pid)
            _record_target(targets_by_pid, child, "live_chain_descendant",
                           seed_descendants=True,
                           launcher_source=child_launcher_source)
            if child_launcher_source is not None:
                seed_launcher_sources[child_pid] = child_launcher_source
            queue.append(child_pid)

    fresh_pids = set(targets_by_pid)
    managed_by_pid: dict[int, dict] = {}
    for target in targets_by_pid.values():
        if target.get("prior_only"):
            continue
        row = idx.get(target["pid"])
        if not isinstance(row, dict):
            continue
        if target["reason"] == "confirmed_launcher":
            continue
        source = (
            "first_confirmed_child_provenance"
            if target["reason"] in {"own_wrapper", "own_wait", "root_wait_brain", "live_chain_descendant"}
            else target["reason"]
        )
        entry = _new_provenance_entry(
            row,
            root_key=root_key,
            agent=agent,
            request_id=request_id,
            source=source,
            now_epoch=now_epoch,
            seed_descendants=bool(target.get("seed_descendants")),
            anchor={
                "pid": launcher_pid,
                "start": launcher_start,
                "source": "confirmed_launcher",
            },
            launcher_source=_target_launcher_source(target),
        )
        if entry is not None:
            entry["fresh_reason"] = target["reason"]
            managed_by_pid[entry["pid"]] = entry

    for entry in valid_priors:
        if entry.get("pid") == launcher_pid:
            continue
        if entry["pid"] in managed_by_pid:
            continue
        row = idx.get(entry["pid"])
        if isinstance(row, dict) and _start_of(row) == entry["start"]:
            managed_by_pid[entry["pid"]] = entry

    for legacy in legacy_priors:
        pid = legacy.get("pid")
        start = legacy.get("start")
        row = idx.get(pid) if isinstance(pid, int) else None
        if (
            isinstance(row, dict)
            and isinstance(start, str)
            and start
            and _start_of(row) == start
            and pid in fresh_pids
        ):
            entry = _new_provenance_entry(
                row,
                root_key=root_key,
                agent=agent,
                request_id=request_id,
                source="legacy_rederived",
                now_epoch=now_epoch,
                seed_descendants=bool(targets_by_pid.get(pid, {}).get("seed_descendants")),
                anchor={
                    "pid": launcher_pid,
                    "start": launcher_start,
                    "source": "legacy",
                },
                launcher_source=_target_launcher_source(targets_by_pid.get(pid, {})),
            )
            if entry is not None:
                managed_by_pid[pid] = entry
                if pid in targets_by_pid:
                    targets_by_pid[pid]["reason"] = "legacy_rederived"
                    targets_by_pid[pid]["source"] = "legacy_rederived"
            continue
        _bump(diagnostics, "legacy_unverifiable_dropped")

    wait_alive = any(t["reason"] == "own_wait" for t in targets_by_pid.values())
    return {
        "snapshot_available": True,
        "targets": list(targets_by_pid.values()),
        "managed_pids": list(managed_by_pid.values()),
        "diagnostics": diagnostics,
        "brain_pid": brain_row.get("pid") if isinstance(brain_row, dict) else st.get("brain_pid"),
        "brain_start": _start_of(brain_row) if isinstance(brain_row, dict) else st.get("brain_start"),
        "wait_alive": wait_alive,
        "discovered_brain": brain_row is not None,
    }


def _agent_state_entry(state: dict, agent: str) -> dict:
    agents = state.get("agents") if isinstance(state.get("agents"), dict) else {}
    entry = agents.get(agent) if isinstance(agents, dict) else None
    return entry if isinstance(entry, dict) else {}


def _prior_wrapper_may_be_alive(st: dict) -> bool:
    if isinstance(st.get("launcher_pid"), int):
        return True
    if isinstance(st.get("pid"), int):
        return True
    managed = st.get("managed_pids")
    if isinstance(managed, list) and any(isinstance(item, dict) for item in managed):
        return True
    return bool(st.get("launching"))


def evaluate_launch_barrier(
    snapshot: list[dict] | None,
    state: dict,
    config: dict,
    agent: str,
    *,
    root_key: str | None = None,
) -> dict:
    """Post-kill one-live-wrapper barrier for the generated executor.

    This is intentionally stricter than planner liveness: after a relaunch
    decision has killed its targets, a fresh snapshot must prove no same-root
    same-agent wrapper or wait process survived before Start-Process runs.
    """
    root_key = root_key or _root_key(config.get("root") or config.get("root_key") or "")
    st = _agent_state_entry(state, agent)
    if snapshot is None:
        blocked = _prior_wrapper_may_be_alive(st)
        return {
            "allow_launch": not blocked,
            "blocked": blocked,
            "reason": "snapshot_unavailable_prior_maybe_alive" if blocked else "no_prior_process",
            "snapshot_available": False,
            "survivor_count": 0,
            "survivors": [],
        }

    survivors: list[dict] = []
    for row in snapshot:
        if not isinstance(row, dict):
            continue
        kind = None
        if parse_agenttalk_wrap_invocation(row.get("command_line"), root_key, agent):
            kind = "own_wrapper"
        elif parse_agenttalk_wait_invocation(row.get("command_line"), root_key, agent):
            kind = "own_wait"
        if kind is None:
            continue
        item = {
            "kind": kind,
            "pid": row.get("pid") if isinstance(row.get("pid"), int) else None,
            "name": _event_token(row.get("name"), "unknown"),
        }
        survivors.append(item)

    blocked = bool(survivors)
    reason = "clear"
    if blocked:
        reason = (
            "same_agent_wrapper_survived"
            if any(s.get("kind") == "own_wrapper" for s in survivors)
            else "same_agent_wait_survived"
        )
    return {
        "allow_launch": not blocked,
        "blocked": blocked,
        "reason": reason,
        "snapshot_available": True,
        "survivor_count": len(survivors),
        "survivors": survivors[:8],
    }


def capture_launch_child_provenance(
    pre_snapshot: list[dict] | None,
    post_snapshot: list[dict] | None,
    *,
    launcher_pid: int | None,
    launcher_start: str | None,
    cfg_agent: dict,
    agent: str,
    root_key: str | None,
    request_id: str | None,
    now_epoch: float,
    launcher_nonce: str | None = None,
    launcher_nonce_injected: bool = False,
) -> tuple[list[dict], dict[str, int]]:
    diagnostics = _diag()
    if not isinstance(launcher_pid, int):
        return [], diagnostics
    launcher_epoch = _iso_epoch(launcher_start)
    if launcher_epoch is None or not isinstance(post_snapshot, list):
        return [], diagnostics
    launcher_source = None
    if launcher_nonce_injected and _valid_launch_nonce(launcher_nonce):
        launcher_source = {
            "pid": launcher_pid,
            "start": launcher_start,
            "nonce": launcher_nonce,
        }
    baseline: set[tuple[int, str]] = set()
    for row in pre_snapshot or []:
        if not isinstance(row, dict):
            continue
        pid = row.get("pid")
        start = _start_of(row)
        if isinstance(pid, int) and isinstance(start, str):
            baseline.add((pid, start))
    out: list[dict] = []
    for row in post_snapshot:
        if not isinstance(row, dict) or row.get("parent_pid") != launcher_pid:
            continue
        pid = row.get("pid")
        start = _start_of(row)
        if not isinstance(pid, int) or not isinstance(start, str) or not start:
            _bump(diagnostics, "unparseable_start_edge")
            continue
        if (pid, start) in baseline:
            continue
        child_epoch = _iso_epoch(start)
        if child_epoch is None:
            _bump(diagnostics, "unparseable_start_edge")
            continue
        if child_epoch < launcher_epoch:
            _bump(diagnostics, "inverted_start_edge")
            continue
        branch = _row_branch_reason(row, root_key, agent)
        if branch is not None:
            _bump(diagnostics, branch)
            continue
        seed = _is_expected_seed_row(row, cfg_agent, agent, root_key)
        entry = _new_provenance_entry(
            row,
            root_key=root_key,
            agent=agent,
            request_id=request_id,
            source="launch_child_provenance",
            now_epoch=now_epoch,
            seed_descendants=seed,
            anchor={
                "pid": launcher_pid,
                "start": launcher_start,
                "source": "confirmed_launcher",
            },
            launcher_source=launcher_source,
        )
        if entry is not None:
            out.append(entry)
    return out, diagnostics


def _wait_row_for(idx: dict[int, dict], agent: str) -> dict | None:
    """The agent's `agenttalk wait --for <agent>` process row, matched by command
    line (degrades to None when command lines are unavailable - we never guess)."""
    for row in idx.values():
        cl = row.get("command_line") or ""
        if "agenttalk" in cl and "wait" in cl and (
                f"--for {agent}" in cl or f"--for={agent}" in cl):
            return row
    return None


def _depth_to_launcher(idx: dict[int, dict], row: dict, launcher_pid: int) -> int | None:
    """Number of parent hops from ``row`` up to a node that is (or is a direct
    child of) ``launcher_pid`` - climbing WITHIN the snapshot. Works even when the
    launcher ROW itself has exited (a forking launcher), because we match on the
    recorded ``parent_pid`` reaching ``launcher_pid``, not on the launcher row
    being present. None if the chain never reaches the launcher."""
    cur, depth, seen = row, 0, set()
    while isinstance(cur, dict):
        cpid = cur.get("pid")
        if cpid in seen:
            return None
        seen.add(cpid)
        if cpid == launcher_pid:
            return depth
        if cur.get("parent_pid") == launcher_pid:
            return depth
        ppid = cur.get("parent_pid")
        nxt = idx.get(ppid) if isinstance(ppid, int) else None
        if nxt is None:
            return None
        cur, depth = nxt, depth + 1
    return None


def _discover_brain(idx: dict[int, dict], agent: str, launcher_pid,
                    brain_pattern: str, launch_epoch: float | None = None,
                    allow_launcher_self: bool = False) -> dict | None:
    """Find the long-lived brain process - NEVER the forking LAUNCHER (test #4).

    ``allow_launcher_self`` FALSE (codex): the launcher (codex.exe) spawns the real
    TUI then EXITS, so the launcher row must be EXCLUDED from every strategy - else
    we pin the launcher, it dies after handoff, and grace expiry false-kills a
    healthy agent. TRUE (claude / non-forking): the launcher IS the brain.

    THREE signals, in order:
    1. up from the agent's live ``wait`` process to the HIGHEST ELIGIBLE
       brain-named ancestor (the TUI ABOVE command-runner/wait but BELOW the
       launcher; needs command lines; survives launcher exit);
    2. name + ancestry to the RECORDED ``launcher_pid`` - an eligible brain-named
       row whose parent chain reaches the launcher, preferring the one CLOSEST to
       the launcher (the TUI is its direct child = depth 0; codex-command-runner.exe
       also matches the 'codex' substring but is depth 1, so it never wins),
       tie-broken by in-the-wait-chain, then started-after-launch, then
       deterministic (start, pid). Null-command-line safe.
    3. the degenerate non-forking case (ONLY when allow_launcher_self): the
       launcher row itself matches the name (claude.exe is its own brain).
    Returns the brain row or None."""
    pat = (brain_pattern or "").lower()

    def _name_matches(row):
        return pat and pat in (row.get("name") or "").lower()

    def _is_launcher(row):
        return isinstance(launcher_pid, int) and row.get("pid") == launcher_pid

    def _eligible(row):
        # a brain candidate must match the pattern AND, for a forking CLI, must
        # NOT be the launcher itself.
        return _name_matches(row) and (allow_launcher_self or not _is_launcher(row))

    def _started_after_launch(row) -> bool:
        # soft guard: if both the candidate start and the launch epoch parse,
        # require the candidate to have started at/after the launch (small slack);
        # otherwise (non-ISO test sentinels / unknown) do NOT reject.
        if launch_epoch is None:
            return True
        se = _iso_epoch(_start_of(row))
        return se is None or se >= float(launch_epoch) - 5.0

    # pids on the wait-ancestor chain (strategy-1 climb + strategy-2 tie-break).
    wait = _wait_row_for(idx, agent)
    wait_chain: set = set()
    if wait is not None:
        cur, seen = wait, set()
        while isinstance(cur, dict):
            cpid = cur.get("pid")
            if cpid in seen:
                break
            seen.add(cpid)
            wait_chain.add(cpid)
            ppid = cur.get("parent_pid")
            cur = idx.get(ppid) if isinstance(ppid, int) else None

    # (1) up from the wait process to the highest ELIGIBLE brain-named ancestor.
    if wait is not None:
        best, seen, cur = None, set(), wait
        while isinstance(cur, dict):
            cpid = cur.get("pid")
            if cpid in seen:
                break
            seen.add(cpid)
            if _eligible(cur):
                best = cur  # keep climbing - the TOPMOST eligible (the TUI), not the launcher
            ppid = cur.get("parent_pid")
            cur = idx.get(ppid) if isinstance(ppid, int) else None
        if best is not None:
            return best
    # (2) name + ancestry to the recorded launcher (null-command-line safe).
    if isinstance(launcher_pid, int):
        cands = []
        for row in idx.values():
            if not _eligible(row) or not _started_after_launch(row):
                continue
            d = _depth_to_launcher(idx, row, launcher_pid)
            if d is None:
                continue
            se = _iso_epoch(_start_of(row))
            cands.append((d,                                       # closest to launcher
                          0 if row.get("pid") in wait_chain else 1,  # prefer the wait chain
                          se if se is not None else float("inf"),    # earliest started
                          row.get("pid") if isinstance(row.get("pid"), int) else 1 << 62,
                          row))
        if cands:
            cands.sort(key=lambda c: c[:4])
            return cands[0][4]
    # (3) degenerate non-forking: the launcher row itself is the brain.
    if (allow_launcher_self and isinstance(launcher_pid, int)
            and launcher_pid in idx and _name_matches(idx[launcher_pid])):
        return idx[launcher_pid]
    return None


def _launcher_managed_set(idx: dict[int, dict], launcher_pid, agent: str,
                          now_epoch: float, *,
                          launch_epoch: float | None = None,
                          prior: list[dict] | None = None) -> list[dict]:
    """Best-effort restart kill set for heartbeat-based liveness.

    Heartbeat freshness is the liveness authority; the process snapshot is only
    used to clean up before relaunch. On Windows, children keep the creator
    ``ParentProcessId`` after the launcher exits, so rows whose parent chain
    reaches the recorded launcher are the best scoped target set for Codex's
    TUI/runner/wait tree. Prior start-matching rows are carried forward so a
    later snapshot with null command lines can still reap known children.
    """
    out: dict[int, dict] = {}

    def _started_after_launch(row) -> bool:
        if launch_epoch is None:
            return True
        se = _iso_epoch(_start_of(row))
        return se is None or se >= float(launch_epoch) - 5.0

    def add(row: dict | None, kind: str) -> None:
        if not isinstance(row, dict):
            return
        pid = row.get("pid")
        if not isinstance(pid, int):
            return
        out[pid] = {"pid": pid, "start": _start_of(row),
                    "kind": kind, "last_seen": now_epoch}

    if isinstance(launcher_pid, int):
        for row in idx.values():
            if row.get("pid") == launcher_pid:
                continue  # launcher itself is killed separately with launcher_start
            if (_depth_to_launcher(idx, row, launcher_pid) is not None
                    and _started_after_launch(row)):
                add(row, "launcher-tree")

    wait = _wait_row_for(idx, agent)
    if wait is not None:
        add(wait, "wait")

    for m in (prior or []):
        pid = m.get("pid")
        if not isinstance(pid, int) or pid in out:
            continue
        if _pid_alive_guarded(idx, pid, m.get("start")):
            out[pid] = {"pid": pid, "start": m.get("start"),
                        "kind": m.get("kind", "runner"), "last_seen": now_epoch}
    return list(out.values())


def _liveness(snapshot: list[dict] | None, st: dict, cfg_agent: dict,
              agent: str, now_epoch: float, *,
              root_key: str | None = None,
              request_id: str | None = None) -> dict:
    """Derive process-discovery facts for one agent (PURE).

    Returns ``snapshot_available`` (False when capture failed), ``brain_pid`` /
    ``brain_start`` (recorded, or freshly DISCOVERED this tick), ``brain_alive``,
    ``wait_alive``, ``managed_pids`` (refreshed), and ``discovered_brain``.
    These fields seed next-state and scoped kill targets; heartbeat freshness,
    not process discovery, decides liveness."""
    attr = _attribution(
        snapshot,
        st,
        cfg_agent,
        agent,
        root_key=root_key,
        request_id=request_id,
        now_epoch=now_epoch,
    )
    if snapshot is None:
        return {"snapshot_available": False, "brain_pid": attr.get("brain_pid"),
                "brain_start": attr.get("brain_start"), "brain_alive": False,
                "wait_alive": False, "managed_pids": attr.get("managed_pids") or [],
                "kill_targets": attr.get("targets") or [],
                "diagnostics": attr.get("diagnostics") or _diag(),
                "discovered_brain": False}
    idx = _snap_index(snapshot)
    lcfg = _liveness_cfg(cfg_agent)
    allow_launcher_self = bool(lcfg.get("allow_launcher_self", False))
    launcher_pid = st.get("launcher_pid")
    if bool(lcfg.get("wrapped", False)):
        # WRAPPED agent (launched THROUGH `agenttalk --root ... wrap --loop`):
        # the wrapper (python) is the long-lived root, and the typed ownership
        # pass decides which same-agent children are safe cleanup targets.
        return {"snapshot_available": True, "brain_pid": None,
                "brain_start": None, "brain_alive": False,
                "wait_alive": bool(attr.get("wait_alive")),
                "managed_pids": attr.get("managed_pids") or [],
                "kill_targets": attr.get("targets") or [],
                "diagnostics": attr.get("diagnostics") or _diag(),
                "discovered_brain": False}
    brain_pid = st.get("brain_pid")
    brain_start = st.get("brain_start")
    # STALE-STATE REPAIR (test #4): a stored brain_pid == the LAUNCHER on a
    # forking CLI is a BAD pin (an older buggy discovery). Treat it as dead and
    # re-discover, so next_state records the real TUI instead of preserving the
    # bad launcher pin.
    bad_launcher_pin = (not allow_launcher_self and brain_pid is not None
                        and brain_pid == launcher_pid)
    brain_alive = (not bad_launcher_pin
                   and _pid_alive_guarded(idx, brain_pid, brain_start))
    discovered = False
    if not brain_alive:
        cand = _discover_brain(idx, agent, launcher_pid,
                               cfg_agent.get("brain_pattern")
                               or lcfg.get("brain_pattern", ""),
                               launch_epoch=st.get("last_launch_epoch"),
                               allow_launcher_self=allow_launcher_self)
        if cand is not None:
            brain_pid, brain_start = cand.get("pid"), _start_of(cand)
            brain_alive, discovered = True, True
        elif bad_launcher_pin:
            # repaired-away the bad pin but found no real brain -> not alive,
            # and clear the stale launcher pin from the reported brain_pid.
            brain_pid, brain_start = None, None
    managed = attr.get("managed_pids") or []
    wait_alive = bool(attr.get("wait_alive")) or _wait_row_for(idx, agent) is not None
    return {"snapshot_available": True, "brain_pid": brain_pid,
            "brain_start": brain_start, "brain_alive": brain_alive,
            "wait_alive": wait_alive, "managed_pids": managed,
            "kill_targets": attr.get("targets") or [],
            "diagnostics": attr.get("diagnostics") or _diag(),
            "discovered_brain": discovered}


def _liveness_cfg(cfg_agent: dict) -> dict:
    """Per-agent liveness config merged over the per-CLI defaults."""
    cli = cfg_agent.get("cli", "claude")
    base = dict(_LIVENESS_DEFAULTS.get(cli, _LIVENESS_DEFAULTS["claude"]))
    for k in ("requires_brain_pid", "brain_pattern", "codex_home_isolation",
              "windows_sandbox", "allow_launcher_self", "wrapped"):
        if k in cfg_agent:
            base[k] = cfg_agent[k]
    return base


def build_report(store: Store, *, now_epoch: float,
                 stuck_after_seconds: float | None = None,
                 suspect_after_seconds: float | None = None,
                 state: dict | None = None,
                 supervisor_config: dict | None = None) -> dict:
    """Point-in-time bus-side liveness snapshot. Read-only.

    ``protected`` is ``operator_facing`` UNION every active ``role=lead`` agent
    (fail-closed - see ``Store.protected_agents``). ``heartbeat_stale`` is True
    when there is no heartbeat or it is older than the stuck threshold
    (``stuck_after_seconds``; ``suspect_after_seconds`` accepted as a back-compat
    alias). The launched-PID liveness is NOT here - only the supervisor knows it
    - but when its ``state`` is passed, the recorded ``session_id`` (and pid) is
    merged for an operator-facing view (session_id is supervisor-local, not a
    bus fact, so it is opt-in via state).

    ``supervisor_config`` (the supervisor.json) is opt-in: when passed, each
    agent's ``heartbeat_stale`` is computed against its PER-AGENT/PER-CLI threshold
    (:func:`resolve_stuck_after`), so the operator-facing report MATCHES the
    planner's per-CLI decision (a wrapped Codex is not shown stale at the global
    threshold while the planner correctly holds to 900s). Without it the single
    global threshold applies (legacy behavior). The resolved per-agent threshold
    is reported as ``stuck_after_seconds`` on each agent entry. The additive
    ``heartbeat_evidence`` field preserves missing/observed/future-skew evidence
    for read-only coordination warnings; planning continues to consume the
    unchanged age and stale fields.
    """
    threshold = stuck_after_seconds
    if threshold is None:
        threshold = suspect_after_seconds
    if threshold is None:
        threshold = float(_DEFAULTS["stuck_after_seconds"])
    cfg = store.load_config()
    roster = cfg.get("agents", []) or []
    roles = cfg.get("roles") or {}
    protected = store.protected_agents()
    sup_cfg = supervisor_config if isinstance(supervisor_config, dict) else None
    sup_agents = (sup_cfg.get("agents") if sup_cfg and isinstance(
        sup_cfg.get("agents"), dict) else {})
    state_agents = (state or {}).get("agents") if isinstance(state, dict) else None
    state_agents = state_agents if isinstance(state_agents, dict) else {}
    agents: dict[str, dict] = {}
    for a in roster:
        # per-agent/per-CLI threshold when the supervisor config is supplied
        # (report parity with the planner); else the single global threshold.
        threshold_a = (resolve_stuck_after(sup_cfg, sup_agents.get(a) or {})
                       if sup_cfg is not None else float(threshold))
        health_timing = resolve_health_timing(sup_cfg or {}, sup_agents.get(a) or {})
        hb = store.read_heartbeat(a)
        hb_age = authoritative_heartbeat_age_seconds(
            hb,
            now_epoch=now_epoch,
            heartbeat_skew_seconds=health_timing["heartbeat_skew_seconds"],
        )
        heartbeat_evidence = (
            HEARTBEAT_EVIDENCE_MISSING
            if hb is None
            else (
                HEARTBEAT_EVIDENCE_FUTURE_SKEW
                if hb_age is None
                else HEARTBEAT_EVIDENCE_OBSERVED
            )
        )
        stale = hb_age is None or hb_age > threshold_a
        health = store.read_health(
            a,
            now_epoch=now_epoch,
            heartbeat=hb,
            ttl_seconds=health_timing["ttl_seconds"],
            heartbeat_skew_seconds=health_timing["heartbeat_skew_seconds"],
        )
        marker = store.read_waiting(a)
        w_pid = marker.get("pid") if isinstance(marker, dict) else None
        w_pid = w_pid if isinstance(w_pid, int) else None
        st = state_agents.get(a) if isinstance(state_agents.get(a), dict) else {}
        agents[a] = {
            "role": roles.get(a) if isinstance(roles.get(a), str) else None,
            "protected": a in protected,
            "heartbeat_age_seconds": hb_age,
            "heartbeat_stale": stale,
            "heartbeat_evidence": heartbeat_evidence,
            "stuck_after_seconds": threshold_a,
            "health": health,
            "waiting": marker is not None,
            "waiting_pid": w_pid,
            "waiting_pid_alive": bool(w_pid is not None and _process_alive(w_pid)),
            "waiting_deadline_epoch": (marker.get("deadline_epoch")
                                       if isinstance(marker, dict) else None),
            "restart_request": _restart_request_with_live_authority(
                store, store.read_restart_request(a)),
            "config_blocked_hold": store.read_config_blocked_hold(a),
            "session_id": st.get("session_id"),  # supervisor-local; None unless state passed
        }
        # Managed lead-loop visibility (lead-loop Slice 1; additive, read-only).
        # Present only when the agent is managed OR a lease file exists. The planner
        # acts on the EXIT marker (WP2) - this surfaces the armed/lease state so the
        # report shows a down managed controller.
        if store.is_managed_lead_loop(a) or store.read_lead_loop_lease(a) is not None:
            # Use the SAME per-agent threshold the report uses for the top-level
            # heartbeat_stale (threshold_a), so the nested lead_loop view never skews
            # from it - a wrapped agent's armed/stealable must agree with the
            # supervisor's stuck threshold, not the 120s store default (WP1 contract).
            agents[a]["lead_loop"] = store.lead_loop_state(
                a, now=now_epoch, heartbeat_stale_after=threshold_a)
        # The controller's EXIT marker (WP2): how a managed lead-loop controller last
        # exited - the planner uses it to NOT relaunch a deliberate stand-down / a
        # blocked acquire (vs a crash, which relaunches). Additive; present only when
        # a marker exists.
        _ll_exit = store.read_lead_loop_exit(a)
        if isinstance(_ll_exit, dict):
            agents[a]["lead_loop_exit"] = _ll_exit
    launch_requests = store.list_launch_requests()
    eph_report: dict[str, dict] = {"active": {}, "orphan_agents": []}
    eph_state = (state or {}).get("ephemeral_reviewers") if isinstance(state, dict) else None
    active_eph = eph_state.get("active") if isinstance(eph_state, dict) else None
    active_eph = active_eph if isinstance(active_eph, dict) else {}
    msgs = None
    for rid, entry in active_eph.items():
        if not isinstance(entry, dict):
            continue
        agent = entry.get("agent")
        requester = entry.get("requested_by")
        completion = {"status": eph.COMPLETION_NONE, "terminal": False,
                      "hold": True, "reason": "no typed review-result"}
        if isinstance(agent, str) and isinstance(requester, str):
            try:
                if msgs is None:
                    msgs = store.valid_messages()
                completion = eph.classify_review_result(
                    msgs, request_id=str(rid), agent=agent, requester=requester)
            except (ValueError, OSError, FileNotFoundError) as e:
                completion = {"status": eph.COMPLETION_MALFORMED, "terminal": False,
                              "hold": True, "reason": f"could not scan evidence: {e}"}
        eph_report["active"][rid] = {
            "request_id": rid,
            "agent": agent,
            "requested_by": requester,
            "phase": entry.get("phase"),
            "deadline_epoch": entry.get("deadline_epoch"),
            "launcher_pid": entry.get("launcher_pid"),
            "launcher_start": entry.get("launcher_start"),
            "completion": completion,
        }
    known_temp = {
        entry.get("agent") for entry in active_eph.values()
        if isinstance(entry, dict) and isinstance(entry.get("agent"), str)
    }
    eph_report["orphan_agents"] = [
        a for a in roster if isinstance(a, str) and a.startswith("adversary-")
        and a not in known_temp
    ]
    return {
        "schema_version": 1,
        "root_key": _root_key(str(store.root.resolve())),
        "now_epoch": now_epoch,
        "now": datetime.fromtimestamp(now_epoch, timezone.utc).isoformat().replace(
            "+00:00", "Z"),
        "kill_switch_active": (store.dir / "supervisor.kill").exists(),
        "roster": list(roster),
        "operator_facing": store.operator_facing(),
        "sole_lead": store.sole_lead(),
        "stuck_after_seconds": threshold,
        "agents": agents,
        "launch_requests": launch_requests,
        "ephemeral_reviewers": eph_report,
    }


_BOOTSTRAP_SUPPORTED_CLIS = {"claude", "codex"}
_BOOTSTRAP_PLACEHOLDER_TOKENS = (
    "REPLACE",
    "REPLACE_WITH_PROJECT_DIR",
    "AGENT_NAME",
    "{AGENT}",
    "<CWD>",
)


def _bootstrap_add(checks: list[dict], check_id: str, status: str, detail: str,
                   *, agent: str | None = None, suggestion: str | None = None,
                   facts: dict | None = None) -> None:
    row = {"id": check_id, "status": status, "detail": detail}
    if agent is not None:
        row["agent"] = agent
    if suggestion:
        row["suggestion"] = suggestion
    if facts:
        row["facts"] = facts
    checks.append(row)


def _bootstrap_has_placeholder(value: object) -> bool:
    if isinstance(value, str):
        upper = value.upper()
        return any(token in upper for token in _BOOTSTRAP_PLACEHOLDER_TOKENS)
    if isinstance(value, list):
        return any(_bootstrap_has_placeholder(item) for item in value)
    if isinstance(value, dict):
        return any(_bootstrap_has_placeholder(item) for item in value.values())
    return False


def _bootstrap_arg_value(args: list, flag: str) -> str | None:
    for i, item in enumerate(args):
        if item == flag and i + 1 < len(args) and isinstance(args[i + 1], str):
            return args[i + 1]
        if isinstance(item, str) and item.startswith(flag + "="):
            return item[len(flag) + 1:]
    return None


def _bootstrap_flag_before(args: list, flag: str, before: str) -> bool:
    try:
        cut = args.index(before)
    except ValueError:
        cut = len(args)
    head = args[:cut]
    return flag in head or any(
        isinstance(item, str) and item.startswith(flag + "=") for item in head
    )


def _bootstrap_launch_tail(args: list) -> list:
    try:
        cut = args.index("--")
    except ValueError:
        return []
    return args[cut + 1:]


def bootstrap_check(store: Store, *, now_epoch: float,
                    supervisor_config: dict | None = None,
                    state: dict | None = None) -> dict:
    """Read-only readiness check for turning a roster into a live team.

    The check is intentionally CLI-neutral: Claude and Codex are both accepted
    managed CLIs, and the wrapper invariants are the same for either one. It
    answers the field-test question "is this identity merely in the roster, or
    is it a configured, fresh, supervised agent that the lead can assign work
    to?"
    """
    cfg = store.load_config()
    roster = [a for a in (cfg.get("agents") or []) if isinstance(a, str)]
    roles = cfg.get("roles") if isinstance(cfg.get("roles"), dict) else {}
    supervisor_config = supervisor_config if isinstance(supervisor_config, dict) else {}
    cfg_agents = (
        supervisor_config.get("agents")
        if isinstance(supervisor_config.get("agents"), dict) else {}
    )
    cfg_agent_names = set(cfg_agents)
    checks: list[dict] = []

    if roster:
        _bootstrap_add(checks, "roster_present", "ok",
                       f"roster has {len(roster)} agent(s)")
    else:
        _bootstrap_add(checks, "roster_missing", "error",
                       "no roster identities are configured",
                       suggestion="run agenttalk init or agenttalk roster add")

    liaison = store.operator_facing()
    if liaison is None:
        _bootstrap_add(
            checks, "operator_facing_missing", "error",
            "no live operator-facing liaison is configured",
            suggestion="run agenttalk roster set-operator-facing <lead-agent>",
        )
    else:
        _bootstrap_add(checks, "operator_facing_present", "ok",
                       f"operator-facing liaison is {liaison}", agent=liaison)

    if cfg_agents:
        _bootstrap_add(checks, "supervisor_agents_present", "ok",
                       f"supervisor.json has {len(cfg_agents)} configured agent(s)")
    else:
        _bootstrap_add(
            checks, "supervisor_agents_missing", "error",
            "supervisor.json has no configured agents",
            suggestion="run agenttalk supervise --init and fill the agents block",
        )

    report = build_report(
        store, now_epoch=now_epoch, state=state if isinstance(state, dict) else None,
        supervisor_config=supervisor_config,
    )
    report_agents = report.get("agents") if isinstance(report.get("agents"), dict) else {}

    for name in sorted(cfg_agents):
        raw_agent = cfg_agents.get(name)
        cfg_agent = raw_agent if isinstance(raw_agent, dict) else None
        if name not in roster:
            _bootstrap_add(
                checks, "supervisor_agent_not_in_roster", "error",
                "supervisor has an agent that is not in the roster",
                agent=name,
                suggestion="add it with agenttalk roster add, or remove it from supervisor.json",
            )
        if cfg_agent is None:
            _bootstrap_add(
                checks, "supervisor_agent_config_invalid", "error",
                "supervisor agent entry is not a JSON object",
                agent=name,
                suggestion="replace this entry with a normal supervisor agent block",
            )
            continue

        cli_name = cfg_agent.get("cli")
        if not isinstance(cli_name, str) or cli_name not in _BOOTSTRAP_SUPPORTED_CLIS:
            _bootstrap_add(
                checks, "supervisor_agent_cli_unsupported", "error",
                f"cli must be one of {sorted(_BOOTSTRAP_SUPPORTED_CLIS)}",
                agent=name,
                facts={"cli": cli_name},
                suggestion="set cli to claude or codex",
            )
        else:
            _bootstrap_add(checks, "supervisor_agent_cli_supported", "ok",
                           f"{cli_name} agent configured", agent=name,
                           facts={"cli": cli_name})

        if cfg_agent.get("auto_restart") is True:
            _bootstrap_add(checks, "supervisor_agent_restart_enabled", "ok",
                           "auto_restart is enabled", agent=name)
        else:
            _bootstrap_add(
                checks, "supervisor_agent_restart_disabled", "warn",
                "auto_restart is not enabled; the supervisor will not relaunch this agent",
                agent=name,
                suggestion="set auto_restart=true for unattended team members",
            )

        wrapped = bool(cfg_agent.get("wrapped"))
        if wrapped:
            _bootstrap_add(checks, "supervisor_agent_wrapped", "ok",
                           "wrapped agent configured", agent=name)
        else:
            _bootstrap_add(
                checks, "supervisor_agent_not_wrapped", "warn",
                "agent is not wrapped; manual-listen supervision is best-effort",
                agent=name,
                suggestion="prefer agenttalk wrap --loop for unattended Claude or Codex agents",
            )

        launch = cfg_agent.get("launch")
        launch = launch if isinstance(launch, dict) else None
        if launch is None:
            _bootstrap_add(
                checks, "supervisor_agent_launch_missing", "error",
                "launch block is missing or invalid",
                agent=name,
                suggestion="fill launch.windows_file and launch.windows_args",
            )
        else:
            windows_file = launch.get("windows_file")
            windows_args = launch.get("windows_args")
            if not isinstance(windows_file, str) or not windows_file.strip():
                _bootstrap_add(
                    checks, "supervisor_agent_launch_file_missing", "error",
                    "launch.windows_file is missing",
                    agent=name,
                    suggestion="set it to python.exe for wrapped agents or the real CLI exe for manual agents",
                )
            elif _bootstrap_has_placeholder(windows_file):
                _bootstrap_add(
                    checks, "supervisor_agent_launch_file_placeholder", "error",
                    "launch.windows_file still contains scaffold placeholder text",
                    agent=name,
                    suggestion="replace it with a real executable path",
                )
            else:
                _bootstrap_add(checks, "supervisor_agent_launch_file_set", "ok",
                               "launch.windows_file is set", agent=name)

            if not isinstance(windows_args, list):
                _bootstrap_add(
                    checks, "supervisor_agent_launch_args_invalid", "error",
                    "launch.windows_args must be a JSON array",
                    agent=name,
                    suggestion="replace windows_args with an array of literal argument tokens",
                )
            elif _bootstrap_has_placeholder(windows_args):
                _bootstrap_add(
                    checks, "supervisor_agent_launch_args_placeholder", "error",
                    "launch.windows_args still contains scaffold placeholder text",
                    agent=name,
                    suggestion="replace the placeholder wrapper or CLI arguments",
                )
            else:
                _bootstrap_add(checks, "supervisor_agent_launch_args_set", "ok",
                               "launch.windows_args is filled", agent=name)

            if wrapped and isinstance(windows_args, list):
                if "wrap" not in windows_args:
                    _bootstrap_add(
                        checks, "supervisor_wrapped_missing_wrap", "error",
                        "wrapped=true but launch args do not call agenttalk wrap",
                        agent=name,
                    )
                if not _bootstrap_flag_before(windows_args, "--root", "wrap"):
                    _bootstrap_add(
                        checks, "supervisor_wrapped_missing_root", "error",
                        "wrapped launch does not include an explicit --root before wrap",
                        agent=name,
                        suggestion="add --root {ROOT} before wrap in windows_args",
                    )
                if "--loop" not in windows_args:
                    _bootstrap_add(
                        checks, "supervisor_wrapped_missing_loop", "error",
                        "wrapped launch is missing --loop",
                        agent=name,
                    )
                if "--" not in windows_args:
                    _bootstrap_add(
                        checks, "supervisor_wrapped_missing_cli_tail", "error",
                        "wrapped launch is missing the -- separator and real CLI tail",
                        agent=name,
                    )
                arg_for = _bootstrap_arg_value(windows_args, "--for")
                if arg_for != name:
                    _bootstrap_add(
                        checks, "supervisor_wrapped_for_mismatch", "error",
                        "wrapped --for does not match the supervisor agent name",
                        agent=name,
                        facts={"wrapped_for": arg_for},
                        suggestion=f"set --for {name}",
                    )
                arg_cli = _bootstrap_arg_value(windows_args, "--cli")
                if isinstance(cli_name, str) and arg_cli != cli_name:
                    _bootstrap_add(
                        checks, "supervisor_wrapped_cli_mismatch", "error",
                        "wrapped --cli does not match the supervisor agent cli",
                        agent=name,
                        facts={"wrapped_cli": arg_cli, "cli": cli_name},
                        suggestion=f"set --cli {cli_name}",
                    )
                tail = _bootstrap_launch_tail(windows_args)
                if not tail:
                    _bootstrap_add(
                        checks, "supervisor_wrapped_cli_tail_empty", "error",
                        "wrapped launch has no real CLI command after --",
                        agent=name,
                    )
                elif _bootstrap_has_placeholder(tail[0]):
                    _bootstrap_add(
                        checks, "supervisor_wrapped_cli_tail_placeholder", "error",
                        "wrapped launch real CLI tail still contains placeholder text",
                        agent=name,
                        suggestion="replace the tail after -- with the real claude.exe or codex.exe command",
                    )

        rpt = report_agents.get(name) if isinstance(report_agents.get(name), dict) else None
        if rpt is None:
            continue
        if bool(rpt.get("heartbeat_stale")):
            _bootstrap_add(
                checks, "supervisor_agent_not_fresh", "error",
                "managed agent has no fresh heartbeat",
                agent=name,
                facts={"heartbeat_age_seconds": rpt.get("heartbeat_age_seconds")},
                suggestion="start the supervisor and wait for this agent to reach HEALTHY_IDLE",
            )
        else:
            _bootstrap_add(
                checks, "supervisor_agent_fresh", "ok",
                "managed agent has a fresh heartbeat",
                agent=name,
                facts={"heartbeat_age_seconds": rpt.get("heartbeat_age_seconds")},
            )

    for name in roster:
        if name in cfg_agent_names:
            continue
        rpt = report_agents.get(name) if isinstance(report_agents.get(name), dict) else None
        fresh = bool(rpt is not None and not rpt.get("heartbeat_stale"))
        if name == liaison:
            if fresh:
                _bootstrap_add(checks, "operator_facing_fresh", "ok",
                               "operator-facing liaison has a fresh heartbeat", agent=name)
            else:
                _bootstrap_add(
                    checks, "operator_facing_not_fresh", "warn",
                    "operator-facing liaison is not supervisor-managed and has no fresh heartbeat",
                    agent=name,
                    suggestion="run a liaison heartbeat/listen hook, or manage the lead-loop separately",
                )
            continue
        role = roles.get(name) if isinstance(roles.get(name), str) else None
        if fresh:
            _bootstrap_add(checks, "manual_roster_agent_fresh", "ok",
                           "roster identity is not supervised but has a fresh heartbeat",
                           agent=name, facts={"role": role})
        else:
            _bootstrap_add(
                checks, "roster_identity_not_live", "warn",
                "roster identity is not supervisor-managed and has no fresh heartbeat",
                agent=name,
                facts={"role": role},
                suggestion="supervise it, retire it, or deliberately ignore it before assigning work",
            )

    summary = {
        "ok": sum(1 for c in checks if c.get("status") == "ok"),
        "warn": sum(1 for c in checks if c.get("status") == "warn"),
        "error": sum(1 for c in checks if c.get("status") == "error"),
    }
    verdict = "error" if summary["error"] else "warn" if summary["warn"] else "ok"
    return {
        "schema_version": 1,
        "root_key": _root_key(str(store.root.resolve())),
        "now_epoch": now_epoch,
        "now": datetime.fromtimestamp(now_epoch, timezone.utc).isoformat().replace(
            "+00:00", "Z"),
        "verdict": verdict,
        "summary": summary,
        "checks": checks,
        "supported_clis": sorted(_BOOTSTRAP_SUPPORTED_CLIS),
    }


def _health_brief(view: dict | None) -> dict:
    state = health_model.label(view)
    age = view.get("age_seconds") if isinstance(view, dict) else None
    warnings = view.get("warnings") if isinstance(view, dict) else []
    return {
        "state": state,
        "age_seconds": age if isinstance(age, (int, float)) else None,
        "warnings": warnings if isinstance(warnings, list) else [],
        "advisory": True,
    }


def _plan_one(name: str, rpt: dict, st: dict, config: dict, cfg_agent: dict,
              liveness: dict, *, now_epoch: float) -> dict:
    """Decide ONE agent's action + next state. PURE - no I/O, no clock.

    Heartbeat freshness is the liveness authority. The process snapshot-derived
    ``liveness`` bundle is only used to carry best-effort kill targets into a
    restart; a missing/incorrect brain PID must never cause a healthy,
    heartbeating agent to be killed.
    """
    backoff = _backoff_cfg(config)
    base, cap = float(backoff["base_seconds"]), float(backoff["cap_seconds"])
    reset_after = float(backoff["reset_after_seconds"])
    suspect_interval = float(config.get(
        "suspect_warn_interval_seconds", _DEFAULTS["suspect_warn_interval_seconds"]))
    grace_seconds = float(config.get("launch_grace_seconds", _DEFAULTS["launch_grace_seconds"]))
    max_readiness_retries = int(config.get(
        "max_readiness_retries", _DEFAULTS["max_readiness_retries"]))
    raw_restart_cooldown = config.get(
        "restart_cooldown_seconds", _DEFAULTS["restart_cooldown_seconds"])
    restart_cooldown = (
        float(raw_restart_cooldown)
        if isinstance(raw_restart_cooldown, (int, float)) and not isinstance(raw_restart_cooldown, bool)
        else float(_DEFAULTS["restart_cooldown_seconds"])
    )
    restart_cooldown = min(60.0, max(30.0, restart_cooldown))
    activity_hook = bool(cfg_agent.get("activity_hook", False))
    _lcfg = _liveness_cfg(cfg_agent)
    # A WRAPPED agent is instrumented BY CONSTRUCTION: the wrap --loop loop writes
    # a heartbeat on every idle bus-wait cycle AND the engine stamps on streaming
    # progress during a turn, so a stale heartbeat genuinely means stuck/dead.
    # That makes wrapped a "can confirm stuck" signal exactly like activity_hook -
    # so wrapped agents recover on stale (instead of warn-only) without needing the
    # PostToolUse hook installed. The per-CLI threshold (resolve_stuck_after) keeps
    # a wrapped CODEX (item-level; silent during a long pure-reasoning gap) from
    # being false-killed mid-reasoning; a wrapped CLAUDE (thinking/text deltas)
    # stays fresh and can run tighter.
    wrapped = bool(_lcfg.get("wrapped", False))
    cli_name = cfg_agent.get("cli", "claude")
    stuck_after = resolve_stuck_after(config, cfg_agent)
    # GUARDRAIL (Codex ruling): for a wrapped CODEX, restart-on-stale below the
    # min threshold is too aggressive (item-level stream => likely false-kill
    # mid-reasoning). REFUSE restart authority (degrade to warn-only) + warn,
    # unless the operator explicitly opts in. We never silently coerce the value.
    allow_low_stuck_after = bool(cfg_agent.get("allow_low_stuck_after", False))
    unsafe_low_codex = (wrapped and cli_name == "codex"
                        and stuck_after < _WRAPPED_CODEX_MIN_STUCK_AFTER
                        and not allow_low_stuck_after)
    # TIMING-INVARIANT GUARD (v0.47.0): a wrapped codex with the per-turn watchdog
    # EFFECTIVELY LIVE must have stuck_after ABOVE the watchdog deadline + margin, else the
    # supervisor would kill + relaunch the wrapper into the same wedge BEFORE the watchdog
    # fires. REFUSE restart-on-stale (warn-only) when it would preempt, unless
    # allow_low_stuck_after. CRITICAL: gate this on the SHARED watchdog_effectively_live
    # predicate (the same one cmd_wrap uses) - if the watchdog is effectively DISABLED
    # (sub-floor turn_elapsed without opt-in), the supervisor KEEPS its normal
    # recover-on-stale authority, so the agent is never left with neither.
    from agenttalk.wrapper import turn_watchdog as _twd
    _wd_cfg = _twd.resolve_turn_watchdog(
        config, cfg_agent, default_enabled=(wrapped and cli_name == "codex"))
    watchdog_live = _twd.watchdog_effectively_live(_wd_cfg)
    watchdog_turn_elapsed = _wd_cfg.turn_elapsed_seconds
    watchdog_preempted = (wrapped and cli_name == "codex" and watchdog_live
                          and stuck_after <= watchdog_turn_elapsed + _WATCHDOG_STUCK_AFTER_MARGIN
                          and not allow_low_stuck_after)
    from agenttalk.wrapper import work_heartbeat as _whb
    _work_hb_problem = None
    if wrapped and cli_name == "claude":
        _whb_cfg = _whb.resolve_work_heartbeat(
            config, cfg_agent, cli=cli_name, mode=_whb.MODE_LOOP)
        _work_hb_problems = list(_whb_cfg.config_errors)
        _work_hb_violation = _whb.interval_violation(
            _whb_cfg, stuck_after_seconds=stuck_after)
        if _work_hb_violation:
            _work_hb_problems.append(_work_hb_violation)
        if not _whb_cfg.enabled:
            _work_hb_problem = "work heartbeat ticker disabled"
        elif _work_hb_problems:
            _work_hb_problem = "; ".join(_work_hb_problems)
    can_confirm_stuck = ((activity_hook or wrapped)
                         and not unsafe_low_codex and not watchdog_preempted
                         and _work_hb_problem is None)
    # the EFFECTIVE isolation flag (per-CLI default merged) - emitted in the plan
    # so the executor seeds CODEX_HOME exactly when the planner assumed it, even
    # if the raw config omits the field (codex impl-review MAJOR).
    codex_home_isolation = bool(_lcfg.get("codex_home_isolation", False))
    windows_sandbox = _lcfg.get("windows_sandbox", "unelevated")  # UAC fix (codex)
    perm_mode = claude_permission_mode(config, cfg_agent)  # Claude unattended mode
    window_style, window_style_warning = resolve_window_style(config, cfg_agent)

    protected = bool(rpt.get("protected"))
    # build_report computes heartbeat_stale per-agent when it is given the
    # supervisor_config (cmd_supervise passes it), but a legacy/global report (no
    # supervisor_config) uses the single global threshold. The planner is the
    # safety authority, so for a WRAPPED agent it ALWAYS re-derives staleness from
    # the reported age against its per-CLI threshold (a codex must tolerate a long
    # silent reasoning gap) - harmless when the report already matched, and the
    # backstop when a global report file is supplied. Non-wrapped agents keep the
    # report's decision unchanged. A wrapped agent that never heartbeated (age
    # None) keeps the report's stale=True.
    hb_stale = bool(rpt.get("heartbeat_stale"))
    if wrapped:
        hb_age = rpt.get("heartbeat_age_seconds")
        if isinstance(hb_age, (int, float)):
            hb_stale = float(hb_age) > stuck_after
    health = rpt.get("health") if isinstance(rpt.get("health"), dict) else {}
    if hb_stale and health_model.label(health) == health_model.STATE_WORKING_SILENT:
        health = dict(health)
        warnings = health.get("warnings") if isinstance(health.get("warnings"), list) else []
        if "advisory-health-conflict" not in warnings:
            health["warnings"] = [*warnings, "advisory-health-conflict"]
    marker = rpt.get("restart_request") or None
    consumed = list(st.get("consumed_rids", []))
    fails = int(st.get("consecutive_fails", 0))
    readiness_fails = int(st.get("readiness_fails", 0))
    backoff_next = float(st.get("backoff_next_epoch", 0.0) or 0.0)
    healthy_since = st.get("healthy_since")
    last_warn = float(st.get("last_warn_epoch", 0.0) or 0.0)

    brain_pid = liveness.get("brain_pid")
    brain_start = liveness.get("brain_start")
    managed = liveness.get("managed_pids") or []
    attributed_targets = liveness.get("kill_targets") or []
    diagnostics = liveness.get("diagnostics") or _diag()

    launching = bool(st.get("launching", False))
    grace_until = float(st.get("launch_grace_until", 0.0) or 0.0)
    readiness_seen = bool(st.get("readiness_seen", False))
    resume_available = bool(st.get("resume_available", False))

    # The FIRST fresh heartbeat after launch is readiness: wait heartbeats cover
    # idle/listening and the activity hook covers tool work. Brain PID discovery
    # is intentionally NOT required; it false-killed healthy Codex agents.
    if not hb_stale and not readiness_seen:
        readiness_seen, launching, resume_available = True, False, True
        readiness_fails = 0   # readiness REACHED -> clear the give-up counter
    in_grace = launching and (not readiness_seen) and now_epoch < grace_until

    # carry-forward: ALL supervisor-owned fields pass THROUGH (BLOCKER-3 lesson -
    # a healthy `none` tick must never drop discovery/liveness state). The
    # volatile snapshot is NEVER stored here (codex discipline note 1).
    nxt = {
        "consecutive_fails": fails, "backoff_next_epoch": backoff_next,
        "healthy_since": healthy_since, "consumed_rids": consumed,
        "last_warn_epoch": last_warn,
        "launcher_pid": st.get("launcher_pid"), "launcher_start": st.get("launcher_start"),
        "brain_pid": brain_pid, "brain_start": brain_start, "managed_pids": managed,
        "launching": launching, "launch_grace_until": grace_until,
        "readiness_seen": readiness_seen, "resume_available": resume_available,
        "readiness_fails": readiness_fails,
        "last_launch_epoch": st.get("last_launch_epoch"),
        "session_id": st.get("session_id"), "launched": bool(st.get("launched", False)),
    }

    def _relaunch_state() -> None:
        nf = fails + 1
        nxt["consecutive_fails"] = nf
        nxt["backoff_next_epoch"] = now_epoch + min(cap, base * (2 ** (nf - 1)))
        nxt["healthy_since"] = None
        # a relaunch starts a fresh grace; readiness must be re-earned and the
        # stale brain pid is cleared (re-discovered after relaunch).
        nxt["readiness_seen"] = False
        nxt["launching"] = True
        nxt["launch_grace_until"] = now_epoch + grace_seconds
        nxt["brain_pid"] = None
        nxt["brain_start"] = None
        nxt["managed_pids"] = []

    def _barrier_backoff_state() -> dict:
        hold = copy.deepcopy(nxt)
        nf = fails + 1
        hold["consecutive_fails"] = nf
        hold["backoff_next_epoch"] = now_epoch + min(cap, base * (2 ** (nf - 1)))
        hold["healthy_since"] = None
        return hold

    def _targets(include_launcher: bool) -> list[dict]:
        # EVERY kill target carries its start-time so the executor can refuse to
        # kill a recycled pid (codex discipline note 2).
        out: list[dict] = []
        for target in attributed_targets:
            if not isinstance(target, dict):
                continue
            if not include_launcher and target.get("reason") == "confirmed_launcher":
                continue
            if isinstance(target.get("pid"), int) and isinstance(target.get("start"), str) and target.get("start"):
                out.append({
                    "pid": target["pid"],
                    "start": target["start"],
                    "reason": target.get("reason") or target.get("source") or "live_chain",
                    "source": target.get("source") or target.get("reason") or "live_chain",
                })
        return out

    def _result(action, *, state, kill_first=False, kill_orphans=False,
                kill_targets=None, clear_marker=None, bypass_backoff=False,
                notify=False, discover_brain=False, reason="",
                barrier_state=None):
        res = {"agent": name, "action": action, "state": state,
               "clear_marker": clear_marker, "kill_first": bool(kill_first),
               "kill_orphans": bool(kill_orphans), "kill_targets": kill_targets or [],
               "bypass_backoff": bool(bypass_backoff), "notify": bool(notify),
               "discover_brain": bool(discover_brain),
               "codex_home_isolation": codex_home_isolation,
               "windows_sandbox": windows_sandbox, "perm_mode": perm_mode,
               "window_style": window_style,
               "window_style_warning": window_style_warning,
               "reason": reason, "cli": None, "launch_mode": None,
               "resume_mode": None, "session_id": None, "session_args": None,
               "health": _health_brief(health),
               "diagnostics": {k: v for k, v in diagnostics.items() if v},
               "next_state": nxt}
        if action in (RELAUNCH, STUCK_RECOVER):
            res.update(_launch_detail({**st, "resume_available": resume_available},
                                      cfg_agent, perm_mode=perm_mode))
            if isinstance(barrier_state, dict):
                res["barrier_state"] = barrier_state
        return res

    # 0) Manual restart-request marker (highest priority).
    if isinstance(marker, dict) and isinstance(marker.get("request_id"), str):
        rid = marker["request_id"]
        auth_ok = (
            marker.get("authority_result") == "authorized"
            and isinstance(marker.get("requested_by"), str)
            and isinstance(marker.get("authorized_by"), str)
            and marker.get("authorized_by") == marker.get("requested_by")
            and marker.get("authority_still_valid", True) is True
        )
        if not auth_ok:
            nxt["last_warn_epoch"] = now_epoch
            return _result(REFUSE_PROTECTED, state="RESTART_UNAUTHORIZED",
                           notify=True,
                           reason="restart-request has no valid authorization marker")
        force_authorized = (
            marker.get("force_protected_authorized") is True
            and isinstance(marker.get("force_protected_authorized_by"), str)
            and marker.get("force_protected_still_authorized", True) is True
        )
        if protected and not force_authorized:
            nxt["last_warn_epoch"] = now_epoch
            return _result(REFUSE_PROTECTED, state="REFUSE_PROTECTED",
                           notify=True, reason="restart of a protected agent requires "
                                               "authorized --force-protected")
        if rid not in consumed:
            live_kill_ack = (
                marker.get("acknowledge_live_protected_kill_authorized") is True
                and marker.get("acknowledge_live_protected_kill_still_authorized", True) is True
            )
            if protected and not hb_stale and not live_kill_ack:
                nxt["last_warn_epoch"] = now_epoch
                return _result(REFUSE_PROTECTED, state="LIVE_PROTECTED_REFUSED",
                               notify=True,
                               reason="protected agent has a fresh heartbeat; repeat the "
                                      "operator-facing request with "
                                      "--acknowledge-live-protected-kill")
            last_launch = st.get("last_launch_epoch")
            if isinstance(last_launch, (int, float)) and now_epoch - float(last_launch) < restart_cooldown:
                return _result(BACKOFF_WAIT, state="RESTART_COOLDOWN",
                               reason=f"manual restart-request {rid} cooling down "
                                      f"until {float(last_launch) + restart_cooldown:.0f} "
                                      f"(requested_by={marker.get('requested_by')})")
            barrier_state = copy.deepcopy(nxt)
            nxt["consumed_rids"] = [*consumed, rid]
            kt = _targets(include_launcher=True)
            _relaunch_state()
            nxt["readiness_fails"] = 0   # operator restart CLEARS a readiness give-up
            nxt["restart_request_state"] = "applied_pending_readiness"
            nxt["pending_restart_request_id"] = rid
            nxt["restart_requested_by"] = marker.get("requested_by")
            nxt["restart_authorized_by"] = marker.get("authorized_by")
            nxt["restart_authority_result"] = marker.get("authority_result")
            nxt["restart_authority_reason"] = marker.get("authority_reason")
            return _result(RELAUNCH, state="MANUAL_RESTART",
                           kill_first=bool(kt), kill_targets=kt, bypass_backoff=True,
                           reason=f"manual restart-request {rid}",
                           barrier_state=barrier_state)
        if not hb_stale and readiness_seen:
            nxt["restart_request_state"] = "readiness_seen"
            return _result(CLEAR_MARKER, state="HEALTHY_IDLE", clear_marker=rid,
                           reason=f"restart {rid} reached readiness; clearing marker")
        # consumed but still stale -> relaunch failed; fall through (no re-bypass).

    # 1) LAUNCHING: still in grace with readiness unresolved. Launcher death and
    # missing/incorrect brain discovery are irrelevant during startup.
    if in_grace:
        return _result(NONE, state="LAUNCHING", discover_brain=not wrapped,
                       reason="in launch grace; awaiting first fresh heartbeat")

    # 2) STUCK_OR_DEAD: heartbeat stale past grace. With the activity hook on (or a
    # WRAPPED agent, instrumented by construction), stale means the agent is
    # neither waiting nor completing tools; restart. Without either signal, a long
    # working turn would not heartbeat, so keep the existing warn-only safety
    # behavior.
    if hb_stale:
        config_blocked_hold = (
            rpt.get("config_blocked_hold")
            if isinstance(rpt.get("config_blocked_hold"), dict) else None
        )
        if config_blocked_hold is not None:
            return _result(NONE, state="CONFIG_BLOCKED",
                           reason="durable config_blocked hold marker is present; "
                                  "HOLDING until operator repair or request-restart")
        # WP2: a managed lead-loop controller that exited DELIBERATELY leaves an EXIT
        # marker the planner honors instead of relaunching (the SYMMETRIC TWIN of the
        # manual-restart override above). A manual request-RESTART (section 0, above) is
        # checked first and OVERRIDES either HOLD; a CRASH writes NO marker, so a crashed
        # controller still relaunches (recovery).
        #   * `stood_down` (a VALID human release/end) -> HOLD UNCONDITIONALLY: relaunching
        #     would defeat the v0.39 stand-down under auto_restart (D-7). It sticks until an
        #     operator request-RESTART re-arms (which clears the marker on the confirmed
        #     relaunch).
        #   * `blocked` (acquire found another owner) -> HOLD ONLY WHILE THAT OWNER IS A
        #     LIVE GUARD (rpt['lead_loop'].armed). If the incumbent has since died / wedged
        #     past TTL / released (not armed), the block has CLEARED -> fall through to
        #     STUCK_RECOVER so this controller relaunches + takes over. (Without the
        #     liveness gate a stale `blocked` marker would PERMANENTLY HOLD - reachable
        #     under default config since wrapped stuck_after < lease TTL - defeating
        #     auto-recovery for a wedged/crashed lead-loop. lead verify P2.)
        ll_exit = rpt.get("lead_loop_exit")
        ll_state = ll_exit.get("state") if isinstance(ll_exit, dict) else None
        if ll_state == "stood_down":
            return _result(NONE, state="LEAD_LOOP_STOOD_DOWN",
                           reason="deliberate lead-loop stand-down (valid human release/"
                                  "end); NOT relaunching until an operator request-restart "
                                  "re-arms")
        if ll_state == "blocked":
            ll_view = rpt.get("lead_loop")
            if isinstance(ll_view, dict) and ll_view.get("armed"):
                return _result(NONE, state="LEAD_LOOP_BLOCKED",
                               reason="lead-loop acquire blocked: another LIVE owner holds "
                                      "the lease; HOLDING (no relaunch)")
            # incumbent owner is gone/dead/wedged -> block cleared -> fall through to recover
        if protected:
            nxt["last_warn_epoch"] = now_epoch
            return _result(WARN_ONLY, state="STUCK_OR_DEAD", notify=True,
                           reason="protected agent heartbeat stale - recover manually")
        if not can_confirm_stuck:
            if unsafe_low_codex:
                warn_reason = (
                    f"wrapped codex stuck_after_seconds={stuck_after:.0f} below the "
                    f"{_WRAPPED_CODEX_MIN_STUCK_AFTER:.0f}s floor - REFUSING "
                    "restart-on-stale (item-level stream would risk a false-kill "
                    "mid-reasoning); raise stuck_after_seconds or set "
                    "allow_low_stuck_after=true to opt in")
            elif watchdog_preempted:
                warn_reason = (
                    f"wrapped codex stuck_after_seconds={stuck_after:.0f} <= turn watchdog "
                    f"deadline {watchdog_turn_elapsed:.0f}s + {_WATCHDOG_STUCK_AFTER_MARGIN:.0f}s "
                    "margin - REFUSING restart-on-stale (it would relaunch into the same "
                    "wedge before the per-turn watchdog fires); raise stuck_after_seconds "
                    "above the deadline+margin or set allow_low_stuck_after=true to opt in")
            elif _work_hb_problem is not None:
                warn_reason = (
                    "heartbeat stale but wrapped Claude work-heartbeat ticker is not "
                    f"authoritative ({_work_hb_problem}); refusing stale recovery until "
                    "doctor/config repair")
            else:
                warn_reason = ("heartbeat stale but NO activity hook - cannot "
                               "confirm stuck; not killed")
            if now_epoch - last_warn >= suspect_interval:
                nxt["last_warn_epoch"] = now_epoch
                return _result(SUSPECT_WARN, state="ACTIVE_OR_BUSY",
                               notify=unsafe_low_codex, reason=warn_reason)
            return _result(NONE, state="ACTIVE_OR_BUSY",
                           reason="suspect (warn rate-limited)")
        # READINESS GIVE-UP CAP (0.31.2 / codex Fix A): a relaunch of an agent that
        # has NOT reached readiness since its last launch (launching + never a fresh
        # heartbeat) is a READINESS-failure relaunch - a resume that never re-enters
        # the listen loop just churns. Count them; after max_readiness_retries, STOP
        # relaunching and surface READINESS_GAVE_UP (no kill, manual intervention),
        # STICKY until a fresh heartbeat (resets the counter above) or an operator
        # restart/clear. A previously-READY agent that just went stale is a normal
        # stuck-recovery: its first relaunch starts the counter at 1; it resets the
        # moment readiness returns.
        never_ready = launching and not readiness_seen
        if now_epoch >= backoff_next:
            if never_ready and readiness_fails >= max_readiness_retries:
                give_up_reason = (
                    f"resume launch never reached first heartbeat after "
                    f"{readiness_fails} relaunch(es); STOPPING relaunch - manual "
                    f"intervention required (restart-request or operator clear). "
                    f"Consider a WRAPPED agent (the wrapper owns the heartbeat).")
                if now_epoch - last_warn >= suspect_interval:
                    nxt["last_warn_epoch"] = now_epoch
                    return _result(READINESS_GAVE_UP, state="READINESS_GAVE_UP",
                                   notify=True, reason=give_up_reason)
                return _result(NONE, state="READINESS_GAVE_UP",
                               reason="readiness gave up (warn rate-limited)")
            kt = _targets(include_launcher=True)
            barrier_state = _barrier_backoff_state()
            _relaunch_state()
            nxt["readiness_fails"] = (readiness_fails + 1) if never_ready else 1
            return _result(STUCK_RECOVER, state="STUCK_OR_DEAD",
                           kill_first=bool(kt), kill_orphans=True,
                           kill_targets=kt,
                           reason="heartbeat stale; best-effort kill + resume",
                           barrier_state=barrier_state)
        return _result(BACKOFF_WAIT, state="STUCK_OR_DEAD",
                       reason=f"heartbeat stale; backing off until {backoff_next:.0f}")

    # 3) HEALTHY_IDLE: fresh heartbeat.
    if healthy_since is None:
        nxt["healthy_since"] = now_epoch
    elif fails and (now_epoch - float(healthy_since)) >= reset_after:
        nxt["consecutive_fails"], nxt["backoff_next_epoch"] = 0, 0.0
    return _result(NONE, state="HEALTHY_IDLE", reason="healthy")


def _store_cfg_from_report(report: dict) -> dict:
    roster = report.get("roster") if isinstance(report.get("roster"), list) else []
    agents = report.get("agents") if isinstance(report.get("agents"), dict) else {}
    roles = {
        a: entry.get("role")
        for a, entry in agents.items()
        if isinstance(entry, dict) and isinstance(entry.get("role"), str)
    }
    cfg = {"agents": [a for a in roster if isinstance(a, str)], "roles": roles}
    liaison = report.get("operator_facing")
    if isinstance(liaison, str):
        cfg["operator_facing"] = liaison
    return cfg


def _ephemeral_kill_targets(snapshot: list[dict] | None, entry: dict,
                            now_epoch: float, *,
                            root_key: str | None = None) -> list[dict]:
    agent = str(entry.get("agent") or "")
    attr = _attribution(
        snapshot,
        entry,
        {"cli": entry.get("cli") or "codex", "wrapped": True},
        agent,
        root_key=root_key or entry.get("root_key"),
        request_id=str(entry.get("request_id") or ""),
        now_epoch=now_epoch,
    )
    out: list[dict] = []
    for target in attr.get("targets") or []:
        if isinstance(target.get("pid"), int) and isinstance(target.get("start"), str) and target.get("start"):
            out.append({
                "pid": target["pid"],
                "start": target["start"],
                "reason": target.get("reason") or target.get("source") or "provenanced_prior",
                "source": target.get("source") or target.get("reason") or "provenanced_prior",
            })
    if attr.get("managed_pids") is not None:
        entry["managed_pids"] = attr.get("managed_pids")
    if attr.get("diagnostics"):
        entry["provenance_diagnostics"] = {
            k: v for k, v in attr["diagnostics"].items() if v
        }
    return out


def _ephemeral_process_alive(snapshot: list[dict] | None, entry: dict) -> bool | None:
    if snapshot is None:
        return None
    return _pid_alive_guarded(_snap_index(snapshot), entry.get("launcher_pid"),
                              entry.get("launcher_start"))


def _ephemeral_next_without(state: dict, request_id: str) -> dict:
    copied = copy.deepcopy(state)
    eph.forget_active(copied, request_id)
    return copied.get("ephemeral_reviewers", {})


def _plan_launch_requests(report: dict, state: dict, config: dict,
                          *, now_epoch: float) -> dict[str, dict]:
    store_cfg = _store_cfg_from_report(report)
    out: dict[str, dict] = {}
    for marker in report.get("launch_requests") or []:
        if not isinstance(marker, dict):
            continue
        rid = marker.get("request_id")
        if not isinstance(rid, str):
            continue
        if marker.get("state", eph.STATE_QUEUED) != eph.STATE_QUEUED:
            out[rid] = {
                "request_id": rid,
                "action": eph.ACTION_NONE,
                "state": marker.get("state"),
                "reason": "request is already claimed or terminal",
            }
            continue
        errors, _profile = eph.validate_launch_request(marker, store_cfg, config)
        if not errors:
            errors = eph.capacity_errors(state, config, now_epoch)
        if errors:
            out[rid] = {
                "request_id": rid,
                "action": eph.ACTION_DENY,
                "state": eph.STATE_DENIED,
                "terminal_state": eph.STATE_DENIED,
                "reason": "; ".join(errors),
                "archive": True,
                "notify": True,
            }
            continue
        out[rid] = {
            "request_id": rid,
            "action": eph.ACTION_LAUNCH,
            "state": eph.STATE_QUEUED,
            "reason": "valid queued ephemeral review request",
            "profile": marker.get("profile"),
            "skill": marker.get("skill"),
            "requested_by": marker.get("requested_by"),
            "revision": (marker.get("scope") or {}).get("revision")
            if isinstance(marker.get("scope"), dict) else None,
        }
    return out


def _plan_ephemeral_active(report: dict, state: dict, config: dict,
                           *, now_epoch: float,
                           snapshot: list[dict] | None = None,
                           root_key: str | None = None) -> dict[str, dict]:
    del config  # reserved for future per-profile completion policy
    state_root = (state or {}).get("ephemeral_reviewers")
    state_active = state_root.get("active") if isinstance(state_root, dict) else {}
    state_active = state_active if isinstance(state_active, dict) else {}
    rpt_root = report.get("ephemeral_reviewers") if isinstance(report.get("ephemeral_reviewers"), dict) else {}
    rpt_active = rpt_root.get("active") if isinstance(rpt_root.get("active"), dict) else {}
    out: dict[str, dict] = {}
    for rid, entry in state_active.items():
        if not isinstance(entry, dict):
            continue
        rpt_entry = rpt_active.get(rid) if isinstance(rpt_active.get(rid), dict) else {}
        completion = rpt_entry.get("completion") if isinstance(rpt_entry.get("completion"), dict) else {}
        if completion.get("terminal") is True:
            kt = _ephemeral_kill_targets(snapshot, entry, now_epoch, root_key=root_key)
            out[rid] = {
                "request_id": rid,
                "agent": entry.get("agent"),
                "action": eph.ACTION_COMPLETE,
                "state": eph.STATE_COMPLETED,
                "terminal_state": eph.STATE_COMPLETED,
                "reason": f"typed review-result status={completion.get('status')}",
                "completion": completion,
                "kill_first": bool(kt),
                "kill_targets": kt,
                "retire": True,
                "archive": True,
                "next_state": _ephemeral_next_without(state, rid),
            }
            continue
        deadline = entry.get("deadline_epoch")
        if isinstance(deadline, (int, float)) and now_epoch >= float(deadline):
            kt = _ephemeral_kill_targets(snapshot, entry, now_epoch, root_key=root_key)
            out[rid] = {
                "request_id": rid,
                "agent": entry.get("agent"),
                "action": eph.ACTION_TIMEOUT,
                "state": eph.STATE_TIMED_OUT,
                "terminal_state": eph.STATE_TIMED_OUT,
                "reason": "ephemeral reviewer timed out without a typed terminal review-result",
                "completion": completion,
                "kill_first": bool(kt),
                "kill_targets": kt,
                "retire": True,
                "archive": True,
                "next_state": _ephemeral_next_without(state, rid),
            }
            continue
        alive = _ephemeral_process_alive(snapshot, entry)
        if entry.get("phase") == eph.STATE_LAUNCHED and alive is False:
            out[rid] = {
                "request_id": rid,
                "agent": entry.get("agent"),
                "action": eph.ACTION_FAILED,
                "state": eph.STATE_FAILED,
                "terminal_state": eph.STATE_FAILED,
                "reason": "ephemeral reviewer process exited without typed terminal review-result; no auto-restart",
                "completion": completion,
                "kill_first": False,
                "kill_targets": [],
                "retire": True,
                "archive": True,
                "next_state": _ephemeral_next_without(state, rid),
            }
            continue
        out[rid] = {
            "request_id": rid,
            "agent": entry.get("agent"),
            "action": eph.ACTION_NONE,
            "state": entry.get("phase", eph.STATE_REQUESTED),
            "reason": completion.get("reason") or "awaiting typed review-result",
            "completion": completion,
            "auto_restart": False,
        }
    for agent in rpt_root.get("orphan_agents") or []:
        if isinstance(agent, str):
            out[f"janitor:{agent}"] = {
                "request_id": None,
                "agent": agent,
                "action": eph.ACTION_JANITOR,
                "state": "orphan",
                "reason": "stale adversary identity has no active launch request",
                "retire": True,
                "archive": False,
            }
    return out


def plan_actions(report: dict, state: dict, config: dict,
                 *, now_epoch: float, snapshot: list[dict] | None = None) -> dict:
    """The SHARED decision table. Returns ``{"now_epoch", "agents": {name: plan}}``
    where each plan has ``action``/``state`` plus ``kill_first``/``kill_orphans``/
    ``kill_targets``/``discover_brain``/``resume_mode``/``next_state`` for the
    executor. Only agents present in BOTH the config and the report are planned
    (config drives what is supervised; the report supplies bus facts).

    ``snapshot`` is the executor's process snapshot (list of rows) interpreted
    per agent by :func:`_liveness`. It is used for best-effort restart kill
    targets only; heartbeat freshness is the liveness authority. The snapshot is
    an INPUT only and is never folded into ``next_state``."""
    cfg_agents = config.get("agents") if isinstance(config.get("agents"), dict) else {}
    rpt_agents = report.get("agents") or {}
    state_agents = state.get("agents") if isinstance(state.get("agents"), dict) else {}
    root_key = report.get("root_key")
    if not isinstance(root_key, str):
        root_key = _root_key(config.get("root") or config.get("root_key") or "")
    out: dict[str, dict] = {}
    for name, cfg_agent in cfg_agents.items():
        if not isinstance(cfg_agent, dict) or not cfg_agent.get("auto_restart", False):
            continue
        rpt = rpt_agents.get(name)
        if not isinstance(rpt, dict):
            continue
        st = state_agents.get(name) if isinstance(state_agents.get(name), dict) else {}
        liveness = _liveness(snapshot, st, cfg_agent, name, now_epoch,
                             root_key=root_key, request_id=None)
        out[name] = _plan_one(name, rpt, st, config, cfg_agent, liveness,
                              now_epoch=now_epoch)
    return {
        "now_epoch": now_epoch,
        "agents": out,
        "launch_requests": _plan_launch_requests(report, state, config,
                                                 now_epoch=now_epoch),
        "ephemeral_reviewers": _plan_ephemeral_active(
            report, state, config, now_epoch=now_epoch, snapshot=snapshot,
            root_key=root_key),
    }


def record_launch(state: dict, agent: str, *, cli: str, pid: int | None,
                  pid_start: str | None = None, now_epoch: float | None = None,
                  grace_seconds: float | None = None,
                  session_id: str | None = None,
                  pre_snapshot: list[dict] | None = None,
                  post_snapshot: list[dict] | None = None,
                  cfg_agent: dict | None = None,
                  root_key: str | None = None,
                  launcher_nonce: str | None = None,
                  launcher_nonce_injected: bool = False,
                  launcher_nonce_source: str | None = None,
                  launcher_nonce_missing_reason: str | None = None) -> dict:
    """Apply a launch-SUCCESS to ``state`` IN PLACE - the rule the generated
    script defers to Python (testable, not PS-internal). ``pid`` is the
    LAUNCHER pid from Start-Process (the short-lived bootstrap for a forking CLI;
    the long-lived ``brain_pid`` is DISCOVERED later by the planner from the
    snapshot). Records the launcher + start-time (anti-reuse), opens a fresh
    launch GRACE, resets readiness, and clears the stale brain so it is
    re-discovered. ``resume_available`` is sticky (a prior session still exists).
    Claude pins its minted ``session_id`` (codex resumes by ``--last``)."""
    agents = state.setdefault("agents", {})
    if not isinstance(agents, dict):
        agents = state["agents"] = {}
    entry = agents.get(agent)
    if not isinstance(entry, dict):
        entry = agents[agent] = {}
    entry["launcher_pid"] = pid
    entry["launcher_start"] = pid_start
    if launcher_nonce_injected and _valid_launch_nonce(launcher_nonce):
        entry["launcher_nonce"] = launcher_nonce
        entry["launcher_nonce_injected"] = True
        entry["launcher_nonce_source"] = launcher_nonce_source or "agenttalk_global_arg"
        entry.pop("launcher_nonce_missing_reason", None)
    else:
        entry.pop("launcher_nonce", None)
        entry.pop("launcher_nonce_source", None)
        entry["launcher_nonce_injected"] = False
        if launcher_nonce_missing_reason:
            entry["launcher_nonce_missing_reason"] = launcher_nonce_missing_reason
        else:
            entry.pop("launcher_nonce_missing_reason", None)
    entry["launching"] = True
    entry["readiness_seen"] = False
    entry["brain_pid"] = None
    entry["brain_start"] = None
    now = now_epoch if now_epoch is not None else datetime.now(timezone.utc).timestamp()
    lcfg = {"cli": cli}
    if isinstance(cfg_agent, dict):
        lcfg.update(cfg_agent)
    launch_children, diagnostics = capture_launch_child_provenance(
        pre_snapshot,
        post_snapshot,
        launcher_pid=pid,
        launcher_start=pid_start,
        launcher_nonce=entry.get("launcher_nonce"),
        launcher_nonce_injected=entry.get("launcher_nonce_injected") is True,
        cfg_agent=lcfg,
        agent=agent,
        root_key=root_key,
        request_id=None,
        now_epoch=now,
    )
    entry["managed_pids"] = launch_children
    entry["provenance_diagnostics"] = {k: v for k, v in diagnostics.items() if v}
    entry["last_launch_epoch"] = now
    if grace_seconds is not None:
        entry["launch_grace_until"] = now + float(grace_seconds)
    # legacy back-compat (non-forking pid_alive path + old tests)
    entry["pid"] = pid
    entry["pid_alive"] = True
    entry["launched"] = True
    if cli == "codex":
        entry["session_id"] = None        # never persist a fake id for codex
    elif session_id:
        entry["session_id"] = session_id  # claude: pin the minted/known id
    return state


def prepare_launch_request(store: Store, state: dict, config: dict, request_id: str,
                           *, now_epoch: float, claimed_by: str = "supervisor") -> dict:
    """Claim and prepare one queued ephemeral launch request.

    Side effects are deliberately before process launch and are request-id
    checked: claim marker, roster temporary identity, send the review-request,
    persist active supervisor state, and return a fully substituted launch spec.
    """
    marker0 = store.read_launch_request(request_id)
    if marker0 is None:
        raise eph.EphemeralError(f"launch request {request_id!r} is absent")
    errors, profile = eph.validate_launch_request(marker0, store.load_config(), config)
    if not errors:
        errors = eph.capacity_errors(state, config, now_epoch)
    if errors:
        raise eph.EphemeralError("; ".join(errors))
    marker = store.claim_launch_request(request_id, claimed_by=claimed_by,
                                        at_epoch=now_epoch)
    if marker is None:
        raise eph.EphemeralError(f"launch request {request_id!r} is already claimed")
    # Revalidate after the claim: the marker is untrusted writable state.
    errors, profile = eph.validate_launch_request(marker, store.load_config(), config)
    if errors or profile is None:
        store.archive_launch_request(
            request_id,
            eph.terminal_archive(marker, terminal_state=eph.STATE_DENIED,
                                 reason="; ".join(errors or ["profile is not allowed"]),
                                 at_epoch=now_epoch),
        )
        raise eph.EphemeralError("; ".join(errors or ["profile is not allowed"]))
    lane_id = marker.get("lane_id") or ((marker.get("scope") or {}).get("lane_id")
                                        if isinstance(marker.get("scope"), dict) else None)
    workspace_path = None
    if lane_id:
        try:
            lane_id = lane_mod.validate_lane_id(str(lane_id))
            lanes_data = lane_mod.load_lanes(store)
            lane = (lanes_data.get("lanes") or {}).get(lane_id)
            if not isinstance(lane, dict):
                raise lane_mod.LaneError(f"lane {lane_id!r} has no active provisioned worktree")
            if lane.get("status") != lane_mod.STATUS_ACTIVE:
                raise lane_mod.LaneError(f"lane {lane_id!r} is not active for launch")
            if not lane.get("worktree_path"):
                raise lane_mod.LaneError(f"lane {lane_id!r} has no provisioned worktree for launch")
            workspace_path = str(Path(lane["worktree_path"]))
            marker["lane_id"] = lane_id
            marker["workspace_path"] = workspace_path
            marker.setdefault("scope", {})["lane_id"] = lane_id
        except lane_mod.LaneError as e:
            store.archive_launch_request(
                request_id,
                eph.terminal_archive(marker, terminal_state=eph.STATE_DENIED,
                                     reason=f"invalid lane launch: {e}",
                                     at_epoch=now_epoch),
            )
            raise eph.EphemeralError(f"invalid lane launch: {e}") from e
    cfg = store.load_config()
    agent = eph.choose_agent_name(request_id, cfg.get("agents", []) or [],
                                  store.retired_agents())
    role = eph.effective_role(marker, profile)
    groups = eph.effective_groups(marker, profile)
    timeout = int(marker.get("timeout_seconds")
                  or eph.config_block(config)["default_timeout_seconds"])
    marker["timeout_seconds"] = timeout
    store.add_agent(agent, role=role, groups=groups)
    try:
        body = eph.review_request_body(marker, agent)
        msg = store.send(
            sender=marker["requested_by"],
            recipient=agent,
            kind="review-request",
            subject=f"ephemeral review {request_id}",
            body=body,
            meta={
                "request_id": request_id,
                "ephemeral_request_id": request_id,
                "evidence_only": "true",
                "counted_signoff": "false",
                "profile": str(marker.get("profile", "")),
                "skill": str(marker.get("skill", "")),
                "revision": str((marker.get("scope") or {}).get("revision", "")),
            },
        )
    except Exception as send_error:
        extra = {"agent": agent}
        try:
            store.retire_agent(agent, reason=f"ephemeral launch {request_id} failed before request send")
        except ValueError as cleanup_error:
            extra["cleanup_error"] = str(cleanup_error)
        store.archive_launch_request(
            request_id,
            eph.terminal_archive(
                marker,
                terminal_state=eph.STATE_FAILED,
                reason=f"failed before review request send: {send_error}",
                at_epoch=now_epoch,
                extra=extra,
            ),
        )
        raise
    store.update_launch_request(request_id, {
        "state": eph.STATE_REQUESTED,
        "agent": agent,
        "review_request_msg_id": msg.id,
        "requested_at": eph.utc_now(),
        "requested_at_epoch": now_epoch,
        "lane_id": lane_id,
        "workspace_path": workspace_path,
    })
    eph.record_prepared(
        state,
        request_id=request_id,
        agent=agent,
        requested_by=marker["requested_by"],
        profile=str(marker.get("profile", "")),
        timeout_seconds=timeout,
        now_epoch=now_epoch,
        review_request_id=msg.id,
    )
    spec = eph.launch_spec(marker, profile, agent)
    if workspace_path:
        spec["lane_id"] = lane_id
        spec["workspace_path"] = workspace_path
        spec["cwd"] = workspace_path
        if spec.get("cli") == "codex":
            launch = spec.setdefault("launch", {})
            args = list(launch.get("windows_args") or [])
            if not any(args[i] == "--add-dir" and i + 1 < len(args)
                       and str(args[i + 1]) == workspace_path for i in range(len(args))):
                args = ["--add-dir", workspace_path, *args]
            launch["windows_args"] = args
    window_style, warning = resolve_window_style(config, profile)
    spec["window_style"] = window_style
    spec["window_style_warning"] = warning
    spec["review_request_msg_id"] = msg.id
    return spec


def record_ephemeral_launch(state: dict, request_id: str, *, pid: int | None,
                            pid_start: str | None = None,
                            now_epoch: float | None = None,
                            timeout_seconds: int | None = None,
                            pre_snapshot: list[dict] | None = None,
                            post_snapshot: list[dict] | None = None,
                            cfg_agent: dict | None = None,
                            root_key: str | None = None,
                            launcher_nonce: str | None = None,
                            launcher_nonce_injected: bool = False,
                            launcher_nonce_source: str | None = None,
                            launcher_nonce_missing_reason: str | None = None) -> dict:
    """Apply an ephemeral wrapper launch success to supervisor state."""
    now = now_epoch if now_epoch is not None else datetime.now(timezone.utc).timestamp()
    result = eph.record_launched(
        state,
        request_id=request_id,
        pid=pid,
        pid_start=pid_start,
        now_epoch=now,
        timeout_seconds=timeout_seconds,
    )
    root = eph.ensure_state(result)
    entry = root["active"].get(request_id)
    if isinstance(entry, dict):
        if launcher_nonce_injected and _valid_launch_nonce(launcher_nonce):
            entry["launcher_nonce"] = launcher_nonce
            entry["launcher_nonce_injected"] = True
            entry["launcher_nonce_source"] = launcher_nonce_source or "agenttalk_global_arg"
            entry.pop("launcher_nonce_missing_reason", None)
        else:
            entry.pop("launcher_nonce", None)
            entry.pop("launcher_nonce_source", None)
            entry["launcher_nonce_injected"] = False
            if launcher_nonce_missing_reason:
                entry["launcher_nonce_missing_reason"] = launcher_nonce_missing_reason
            else:
                entry.pop("launcher_nonce_missing_reason", None)
        agent = entry.get("agent")
        lcfg = {"cli": "codex", "wrapped": True}
        if isinstance(cfg_agent, dict):
            lcfg.update(cfg_agent)
        if isinstance(agent, str):
            launch_children, diagnostics = capture_launch_child_provenance(
                pre_snapshot,
                post_snapshot,
                launcher_pid=pid,
                launcher_start=pid_start,
                launcher_nonce=entry.get("launcher_nonce"),
                launcher_nonce_injected=entry.get("launcher_nonce_injected") is True,
                cfg_agent=lcfg,
                agent=agent,
                root_key=root_key,
                request_id=request_id,
                now_epoch=now,
            )
            entry["managed_pids"] = launch_children
            entry["provenance_diagnostics"] = {k: v for k, v in diagnostics.items() if v}
    return result


def archive_ephemeral_request(store: Store, state: dict, request_id: str, *,
                              terminal_state: str, reason: str,
                              now_epoch: float | None = None,
                              completion: dict | None = None,
                              retire: bool = True) -> dict:
    """Archive a terminal launch request and tombstone its temporary identity."""
    marker = store.read_launch_request(request_id)
    root = eph.ensure_state(state)
    entry = root["active"].get(request_id)
    entry = entry if isinstance(entry, dict) else {}
    agent = entry.get("agent") or (marker or {}).get("agent")
    retire_error = None
    if retire and isinstance(agent, str):
        try:
            cfg = store.load_config()
            if agent in (cfg.get("agents") or []):
                store.retire_agent(agent, reason=f"ephemeral review {request_id}: {terminal_state}")
        except ValueError as e:
            retire_error = str(e)
    extra = {"completion": completion or {}, "agent": agent}
    if retire_error:
        extra["retire_error"] = retire_error
    payload = eph.terminal_archive(
        marker,
        terminal_state=terminal_state,
        reason=reason,
        at_epoch=now_epoch,
        extra=extra,
    )
    store.archive_launch_request(request_id, payload)
    eph.forget_active(state, request_id)
    return state


def janitor_retire_ephemeral_orphan(store: Store, agent: str) -> bool:
    """Retire a stale active adversary-* identity left without supervisor state."""
    if not isinstance(agent, str) or not agent.startswith("adversary-"):
        return False
    try:
        cfg = store.load_config()
        if agent not in (cfg.get("agents") or []):
            return False
        store.retire_agent(agent, reason="ephemeral reviewer startup janitor")
        return True
    except ValueError:
        return False


