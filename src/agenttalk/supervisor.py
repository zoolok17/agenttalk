def session_args(cli: str, mode: str, session_id: str | None,
                 cfg_agent: dict | None = None,
                 perm_mode: str = "bypassPermissions") -> list[str]:
    """The session CLI args for a (cli, mode) launch as a LIST of literal
    tokens. ``mode`` is "fresh" or "resume". A per-agent ``session`` config
    overrides the built-in token lists. ``{SESSION_ID}`` is substituted when
    ``session_id`` is known (resume); ``{PERM_MODE}`` is substituted from
    ``perm_mode`` (Claude's unattended permission mode). Pure + deterministic -
    each token is one argument, so the generated command line is unit-testable
    and quote-safe."""
    cli = cli if cli in _SESSION_DEFAULTS else "claude"
    # Coerce to dict only when it IS a dict (same corrupt-config class as the other
    # per-agent resolvers): a truthy non-dict per-agent supervisor.json entry must not
    # crash launch session-arg resolution on cfg_agent.get(...).
    cfg_agent = cfg_agent if isinstance(cfg_agent, dict) else {}
    key = "fresh" if mode == "fresh" else "resume"
    tokens = _SESSION_DEFAULTS[cli][key]
    over = cfg_agent.get("session")
    if isinstance(over, dict) and isinstance(over.get(key), list):
        tokens = over[key]

    def _sub(t):
        if t == "{PERM_MODE}":
            return perm_mode
        if session_id and t == "{SESSION_ID}":
            return session_id
        return t
    result = [_sub(t) for t in tokens]
    # codex hook-trust (0.31.1): when the codex activity hook is installed
    # (activity_hook=true), the `heartbeat --hook` command's changed HASH
    # re-triggers codex's hook-trust review, which PROMPTS and would strand an
    # unattended non-wrapped codex before its first heartbeat. Inject the
    # documented GLOBAL --dangerously-bypass-hook-trust (prepended, so it sits
    # BEFORE the subcommand) so the supervisor's OWN agenttalk hook runs
    # un-prompted. A wrapped codex never reaches here (launch_mode=wrap returns
    # session_args=[]); a codex without the activity hook has no prompt to bypass;
    # an operator who already added the flag is not double-flagged.
    if (cli == "codex" and cfg_agent.get("activity_hook")
            and "--dangerously-bypass-hook-trust" not in result):
        result = ["--dangerously-bypass-hook-trust", *result]
    return result


def claude_permission_mode(config: dict, cfg_agent: dict) -> str:
    """Resolve Claude's unattended permission mode: per-agent override, else the
    top-level ``claude_permission_mode`` knob, else ``bypassPermissions``."""
    for src in (cfg_agent, config):
        if isinstance(src, dict) and isinstance(src.get("claude_permission_mode"), str):
            return src["claude_permission_mode"]
    return "bypassPermissions"


# --- v0.75.0 runtime ergonomics: per-agent model + reasoning_effort ------------
#
# Per-CLI CLOSED reasoning-effort sets (BUILD-CONFIRMED, 2026-07-13, this session):
#   codex  (codex-cli 0.144.1): the `ReasoningEffortParam` enum surfaced by codex
#          is {none, minimal, low, medium, high, xhigh}; `low|medium|high|xhigh`
#          were LIVE-honored on the default account model (returned OK). We expose
#          the confirmed ergonomic subset below. `none` (disable reasoning) and the
#          undocumented `max` CLI alias are intentionally excluded. NOTE: a specific
#          model may still reject an in-enum value at request time (e.g. this
#          account's model rejects `minimal`) — the allow-list is a launch-time typo
#          guard, not a per-model validator (documented limitation).
#   claude (Claude Code 2.1.207): `--effort {low,medium,high,xhigh,max}` (from
#          `claude --help`; the full wrapped argv accepts it fresh + resume).
_CODEX_EFFORTS = frozenset({"minimal", "low", "medium", "high", "xhigh"})
_CLAUDE_EFFORTS = frozenset({"low", "medium", "high", "xhigh", "max"})
_REASONING_EFFORTS = {"codex": _CODEX_EFFORTS, "claude": _CLAUDE_EFFORTS}


def validate_model(raw: object, *, source: str = "per-agent") -> tuple[str | None, str | None]:
    """Validate a model value (warn + drop, never brick launch). Returns
    ``(value|None, warning|None)``. Absent -> ``(None, None)``. A non-str, empty,
    or LEADING-DASH value (would be parsed as a flag) -> ``(None, warning)``."""
    if raw is None:
        return None, None
    if not isinstance(raw, str) or not raw.strip():
        return None, (f"invalid {source} model={raw!r}; expected a non-empty string; "
                      "ignoring (provider default applies)")
    value = raw.strip()
    if value.startswith("-"):
        return None, (f"invalid {source} model={raw!r}; must not start with '-' "
                      "(would parse as a flag); ignoring")
    return value, None


def validate_reasoning_effort(raw: object, cli: str,
                              *, source: str = "per-agent") -> tuple[str | None, str | None]:
    """Validate a reasoning-effort value against the per-CLI closed set (case-folded).
    Returns ``(value|None, warning|None)``. Absent -> ``(None, None)``. Unknown /
    wrong-CLI / non-str -> ``(None, warning)`` (warn + drop)."""
    if raw is None:
        return None, None
    allowed = _REASONING_EFFORTS.get(cli, frozenset())
    if not isinstance(raw, str) or not raw.strip():
        return None, (f"invalid {source} reasoning_effort={raw!r}; expected a string; ignoring")
    value = raw.strip().casefold()
    if value not in allowed:
        return None, (f"invalid {source} reasoning_effort={raw!r} for cli {cli!r}; "
                      f"expected one of {sorted(allowed)}; ignoring")
    return value, None


