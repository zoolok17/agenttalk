def resolve_window_style(config: dict, cfg_agent: dict) -> tuple[str, str | None]:
    """Resolve the supervised Windows launch style.

    Per-agent ``window_style`` wins over the global setting. Invalid values are
    rejected visibly by returning a warning and falling back to Hidden, which is
    the least-clutter default for unattended fleets.
    """
    config = config if isinstance(config, dict) else {}
    cfg_agent = cfg_agent if isinstance(cfg_agent, dict) else {}
    for source_name, src in (("per-agent", cfg_agent), ("global", config)):
        if "window_style" not in src:
            continue
        raw = src.get("window_style")
        if isinstance(raw, str):
            normalized = raw.strip().lower()
            if normalized in _WINDOW_STYLES:
                return _WINDOW_STYLES[normalized], None
        return (
            _WINDOW_STYLE_DEFAULT,
            f"invalid {source_name} window_style={raw!r}; expected hidden|minimized|normal; "
            "defaulting to hidden",
        )
    return _WINDOW_STYLE_DEFAULT, None


def resolve_stuck_after(config: dict, cfg_agent: dict) -> float:
    """The per-agent heartbeat-stale threshold (PURE). An explicit per-agent
    ``stuck_after_seconds`` wins; else a WRAPPED agent uses the per-CLI default
    (:data:`_WRAPPED_STUCK_AFTER_DEFAULTS`); else the global ``stuck_after_seconds``
    (config, then the built-in default). Non-wrapped agents keep the existing
    global behavior."""
    config = config if isinstance(config, dict) else {}
    gt = config.get("stuck_after_seconds")
    global_threshold = float(gt) if isinstance(gt, (int, float)) and not isinstance(
        gt, bool) else float(_DEFAULTS["stuck_after_seconds"])
    # Coerce to dict only when it IS a dict: a `... or {}` rescues only FALSY values,
    # so a TRUTHY non-dict cfg_agent (a corrupt/hand-edited supervisor.json per-agent
    # entry) would slip through and crash cfg_agent.get(...). Fixes the status/doctor
    # regression (via resolve_timing) AND a pre-existing supervise --report crash.
    cfg_agent = cfg_agent if isinstance(cfg_agent, dict) else {}
    v = cfg_agent.get("stuck_after_seconds")
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return float(v)
    if bool(cfg_agent.get("wrapped", False)):
        cli = cfg_agent.get("cli", "claude")
        return float(_WRAPPED_STUCK_AFTER_DEFAULTS.get(cli, global_threshold))
    return global_threshold


def resolve_dead_letter_caps(config: dict, cfg_agent: dict) -> tuple[int, int]:
    """The per-agent dead-letter caps (PURE): (K_poison, K_escalate). A per-agent
    ``dead_letter.{max_attempts,escalate_after_attempts}`` wins; else the global config
    block; else :data:`_DEFAULTS`. ``0`` disables that cap (debug only - the shipped
    default is ON). Mirrors resolve_stuck_after's per-agent->global->default chain."""
    defaults = _DEFAULTS["dead_letter"]
    # Coerce to dict only when it IS a dict (a `... or {}` rescues only FALSY values):
    # a corrupt supervisor.json with a truthy non-dict config / per-agent entry / nested
    # dead_letter block must NOT crash cap resolution (which would take down `wrap --loop`
    # startup and the planner). Same corrupt-config class as resolve_stuck_after.
    config = config if isinstance(config, dict) else {}
    cfg_agent = cfg_agent if isinstance(cfg_agent, dict) else {}
    gcfg = config.get("dead_letter")
    gcfg = gcfg if isinstance(gcfg, dict) else {}
    acfg = cfg_agent.get("dead_letter")
    acfg = acfg if isinstance(acfg, dict) else {}

    def _pick(key: str) -> int:
        for src in (acfg, gcfg):
            v = src.get(key)
            if isinstance(v, int) and not isinstance(v, bool) and v >= 0:
                return v
        return int(defaults[key])

    return _pick("max_attempts"), _pick("escalate_after_attempts")


def resolve_health_timing(config: dict, cfg_agent: dict) -> dict:
    """Resolve advisory health freshness bounds.

    Per-agent ``health.{ttl_seconds,heartbeat_skew_seconds}`` wins over global
    ``health``. Legacy flat keys are accepted for operators hand-editing early
    configs. Health is advisory; these bounds only decide whether a health file
    reads as ``unknown``.
    """
    defaults = _DEFAULTS["health"]
    config = config if isinstance(config, dict) else {}
    cfg_agent = cfg_agent if isinstance(cfg_agent, dict) else {}
    g = config.get("health")
    g = g if isinstance(g, dict) else {}
    a = cfg_agent.get("health")
    a = a if isinstance(a, dict) else {}

    def _pick(key: str, flat: str) -> float:
        for src, src_key in ((a, key), (cfg_agent, flat), (g, key), (config, flat)):
            v = src.get(src_key)
            if isinstance(v, (int, float)) and not isinstance(v, bool) and v >= 0:
                return float(v)
        return float(defaults[key])

    return {
        "ttl_seconds": _pick("ttl_seconds", "health_ttl_seconds"),
        "heartbeat_skew_seconds": _pick(
            "heartbeat_skew_seconds", "health_heartbeat_skew_seconds"),
    }

# Per-CLI session-argument templates, as LISTS of literal tokens (so the
